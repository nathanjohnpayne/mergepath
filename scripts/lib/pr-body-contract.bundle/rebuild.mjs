#!/usr/bin/env node
// Hub-only rebuild or verification for the standalone PR-body-contract runtime bundle.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
  copyFileSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const mode = process.argv[2];
if (mode !== '--check' && mode !== '--write') {
  process.stderr.write('usage: rebuild.mjs (--check|--write)\n');
  process.exit(2);
}

const bundleDir = dirname(fileURLToPath(import.meta.url));
const libDir = dirname(bundleDir);
const sourcePath = join(libDir, 'pr-body-contract.source.mjs');
const runtimePath = join(libDir, 'pr-body-contract.mjs');
const packagePath = join(bundleDir, 'package.json');
const lockPath = join(bundleDir, 'package-lock.json');

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function packageRootForInput(tempDir, inputPath) {
  const absolute = resolve(tempDir, inputPath);
  const parts = relative(tempDir, absolute).split(sep);
  const marker = parts.indexOf('node_modules');
  if (marker === -1 || marker === parts.length - 1) return null;
  const packageEnd = parts[marker + 1].startsWith('@') ? marker + 3 : marker + 2;
  if (packageEnd > parts.length) return null;
  return join(tempDir, ...parts.slice(0, packageEnd));
}

function licenseFile(packageRoot) {
  return readdirSync(packageRoot)
    .filter((name) => /^(license|copying)(\..*)?$/i.test(name))
    .sort((left, right) => left.localeCompare(right))[0] ?? null;
}

function notices(tempDir, metadata, lock) {
  const roots = new Set();
  for (const inputPath of Object.keys(metadata.inputs)) {
    const root = packageRootForInput(tempDir, inputPath);
    if (root) roots.add(root);
  }

  const packages = [...roots].map((root) => {
    const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
    const lockKey = relative(tempDir, root).split(sep).join('/');
    const licenseName = licenseFile(root);
    if (!licenseName) throw new Error(`${manifest.name}: no packaged LICENSE or COPYING file`);
    return {
      name: manifest.name,
      version: manifest.version,
      license: manifest.license ?? 'UNKNOWN',
      source: lock.packages[lockKey]?.resolved ?? 'UNKNOWN',
      text: readFileSync(join(root, licenseName), 'utf8').replace(/\r\n/g, '\n'),
    };
  }).sort((left, right) => left.name.localeCompare(right.name));

  const lines = [
    '',
    '// THIRD-PARTY NOTICES: generated from esbuild metafile inputs.',
    '// The source lock is scripts/lib/pr-body-contract.bundle/package-lock.json.',
  ];
  for (const item of packages) {
    lines.push('//');
    lines.push(`// BEGIN ${item.name}@${item.version}`);
    lines.push(`// Source: ${item.source}`);
    lines.push(`// Declared license: ${item.license}`);
    // A bare comment preserves a blank license line without producing trailing
    // whitespace in the generated source. Package tarballs occasionally carry
    // spaces on blank lines; those are formatting, not license text.
    for (const line of item.text.split('\n')) lines.push(line === '' ? '//' : `// ${line}`);
    lines.push(`// END ${item.name}@${item.version}`);
  }
  return `${lines.join('\n')}\n`;
}

function build(tempDir) {
  copyFileSync(packagePath, join(tempDir, 'package.json'));
  copyFileSync(lockPath, join(tempDir, 'package-lock.json'));
  copyFileSync(sourcePath, join(tempDir, 'input.mjs'));
  execFileSync('npm', ['ci', '--ignore-scripts', '--no-audit', '--no-fund'], {
    cwd: tempDir,
    stdio: 'inherit',
  });
  const outputPath = join(tempDir, 'runtime.mjs');
  const metafilePath = join(tempDir, 'metafile.json');
  execFileSync(join(tempDir, 'node_modules', '.bin', 'esbuild'), [
    'input.mjs',
    '--bundle',
    '--platform=node',
    '--format=esm',
    '--target=node22',
    '--legal-comments=inline',
    `--metafile=${metafilePath}`,
    `--outfile=${outputPath}`,
  ], { cwd: tempDir, stdio: 'inherit' });
  const raw = readFileSync(outputPath, 'utf8');
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'));
  const metadata = JSON.parse(readFileSync(metafilePath, 'utf8'));
  // These two micromark comments configure its upstream lint rules. Remove
  // them so they neither re-enable a rule inside this generated artifact nor
  // produce unused-disable diagnostics under the consumer's ESLint config.
  const body = (raw.startsWith('#!') ? raw.slice(raw.indexOf('\n') + 1) : raw)
    .replaceAll(' /* eslint-disable no-bitwise */', '')
    .replaceAll(' /* eslint-enable no-bitwise */', '');
  const output = [
    '#!/usr/bin/env node',
    '// Generated by scripts/lib/pr-body-contract.bundle/rebuild.mjs; DO NOT EDIT.',
    '/* eslint-disable -- Generated dependency bundle; lint the readable source instead. */',
    `// Source SHA-256: ${sha256(readFileSync(sourcePath))}`,
    body.trimEnd(),
    notices(tempDir, metadata, lock).trimEnd(),
    '',
  ].join('\n');
  if (/^import .* from ['"](?!node:)/m.test(output)) {
    throw new Error('bundle retained a non-Node runtime import');
  }
  return output;
}

const tempDir = mkdtempSync(join(tmpdir(), 'mergepath-pr-body-contract-'));
try {
  const output = build(tempDir);
  if (mode === '--write') {
    writeFileSync(runtimePath, output);
    process.stdout.write(`wrote ${runtimePath} (${Buffer.byteLength(output)} bytes)\n`);
  } else if (!existsSync(runtimePath) || readFileSync(runtimePath, 'utf8') !== output) {
    process.stderr.write('pr-body-contract bundle is stale; run rebuild.mjs --write\n');
    process.exitCode = 1;
  } else {
    process.stdout.write(`pr-body-contract bundle is current (${sha256(output)})\n`);
  }
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}

def _shebang_cases():
    """`env` resolution, pinned on its own rather than only through a file.

    #1012's discovery reduced `#!/usr/bin/env -S bash -e` to `-S`, so the
    file was not shell "at all" and a tree containing nothing but that script
    reported PASS.  Testing the resolver directly means the property survives
    even when the file-selection fallback would have read the file anyway.
    """
    failures = []
    for line, expected in SHEBANG_CASES:
        got = resolve_shebang(line)
        if got != expected:
            failures.append(
                "shebang %r resolved to %r, expected %r" % (line, got, expected)
            )
    return failures


def _pragma_cases():
    """The pragma's reason is MANDATORY, on emitting and non-emitting lines.

    Asserted against `scan_text` directly rather than through the oracle,
    because "a bare pragma is rejected" is a property of the MECHANISM, not of
    what bash does -- and on a non-emitting line the oracle has nothing to say.
    That is precisely where a bare pragma is otherwise invisible.
    """
    failures = []
    cases = [
        (
            "bare-on-emitter",
            'echo "$GH_TOKEN"  # ' + PRAGMA + ":\n",
            True,
        ),
        (
            "bare-on-non-emitter",
            'other="$GH_TOKEN"  # ' + PRAGMA + ":\n",
            True,
        ),
        (
            "bare-trailing-whitespace",
            'echo "$GH_TOKEN"  # ' + PRAGMA + ":   \n",
            True,
        ),
        (
            "with-reason",
            'echo "$GH_TOKEN"  # ' + PRAGMA + ": a written reason\n",
            False,
        ),
    ]
    for cid, body, expect_error in cases:
        _findings, pragma_errors = scan_text(
            "#!/usr/bin/env bash\n" + body, "pragma/" + cid
        )
        if expect_error and not pragma_errors:
            failures.append(
                "pragma %s: a bare `%s:` with no reason was accepted" % (cid, PRAGMA)
            )
        if not expect_error and pragma_errors:
            failures.append(
                "pragma %s: a pragma WITH a reason was rejected (%s)"
                % (cid, pragma_errors)
            )
    return failures


def _file_selection_cases(tmp):
    """A file bash will execute is a file the gate reads.

    The oracle here runs the file THROUGH ITS OWN SHEBANG, so the axis under
    test is the file-selection one: whichever interpreter the kernel picks is
    the one whose verdict the discovery has to match.  When the named
    interpreter is not installed on the machine running the suite the launch
    fails, and the case falls back to the resolved bash and says so in any
    failure it reports -- a fixture that could not be launched is never scored
    as a clean one.
    """
    failures = []
    body = 'echo "$GH_TOKEN"\n'
    for cid, filename, shebang, expect_shell in FILE_SELECTION_CASES:
        root = os.path.join(tmp, "fs-" + cid)
        os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
        path = os.path.join(root, "scripts", filename)
        header = shebang + (
            "GH_TOKEN='" + SENTINEL + "'\n" if expect_shell else "pass\n"
        )
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(header + (body if expect_shell else ""))
        os.chmod(path, 0o755)
        findings, errors, count = scan_tree(root)
        if expect_shell:
            if count != 1:
                failures.append(
                    "file-selection %s: discovery classified the file as "
                    "non-shell (scanned %d, errors=%s)" % (cid, count, errors)
                )
                continue
            if not findings:
                failures.append(
                    "file-selection %s: file was read but the leak was not "
                    "reported" % cid
                )
            # Ground truth: does the kernel actually run this file, and does
            # the sentinel reach a stream when it does?  `run_via=[]` runs the
            # file ITSELF, so the interpreter is whichever one the shebang
            # names -- which is the whole axis this case is about.
            leaked, _out, _err = run_oracle(
                "", root, os.path.join("scripts", filename),
                shebang=header + body, run_via=[],
            )
            ran_as = "its own shebang"
            if leaked is not True:
                # The shebang did not carry the file to a working interpreter
                # HERE, in one of the two ways that shows up: the launch
                # raised (the named interpreter is absent -- `dash`, `ksh`
                # and `zsh` are not on every runner, and a no-shebang fixture
                # is ENOEXEC by construction), or something ran and wrote
                # nothing (macOS `env` rejects GNU's `--split-string`).
                #
                # That is an environment fact rather than a verdict about
                # file selection, so the case falls back to the resolved bash
                # and RECORDS which interpreter answered.  What it must not
                # do is score the non-answer as clean, which is what testing
                # only `is False` -- and never `is None` -- quietly did.
                leaked, _out, _err = run_oracle(
                    "", root, os.path.join("scripts", filename),
                    shebang=header + body,
                )
                ran_as = "the resolved bash (its shebang did not run it here)"
            if leaked is not True:
                failures.append(
                    "file-selection %s: ran under %s and the sentinel did NOT "
                    "reach a stream -- the fixture is not measuring what it "
                    "claims (%s)"
                    % (cid, ran_as, (_err or "").strip() or "no stderr")
                )
        else:
            if count != 0:
                failures.append(
                    "file-selection %s: a non-shell file was read as shell" % cid
                )

    # CRLF
    root = os.path.join(tmp, "fs-crlf")
    os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
    path = os.path.join(root, "scripts", "crlf.sh")
    with open(path, "wb") as fh:
        fh.write(
            ("#!/usr/bin/env bash\nGH_TOKEN='" + SENTINEL + "'\necho \"$GH_TOKEN\"\n")
            .replace("\n", "\r\n")
            .encode()
        )
    findings, _errors, count = scan_tree(root)
    if count != 1 or not findings:
        failures.append("file-selection crlf: CRLF file not read or not reported")

    # symlink
    root = os.path.join(tmp, "fs-symlink")
    os.makedirs(os.path.join(root, "scripts", "real"), exist_ok=True)
    target = os.path.join(root, "scripts", "real", "leak.sh")
    with open(target, "w", encoding="utf-8") as fh:
        fh.write("#!/usr/bin/env bash\nGH_TOKEN='x'\necho \"$GH_TOKEN\"\n")
    link = os.path.join(root, "scripts", "link.sh")
    try:
        os.symlink(target, link)
        findings, _errors, count = scan_tree(root)
        if count != 2:
            failures.append(
                "file-selection symlink: expected both the target and the "
                "symlink to be read, scanned %d" % count
            )
    except OSError:
        pass
    return failures


def _discovery_failure_cases(tmp):
    """Discovery failures are fatal, never a clean tree."""
    failures = []

    # 1. a tree with no shell files at all
    root = os.path.join(tmp, "disc-empty")
    os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
    with open(os.path.join(root, "scripts", "notes.md"), "w") as fh:
        fh.write("# nothing\n")
    _f, errors, count = scan_tree(root)
    if count != 0 or not errors:
        failures.append(
            "discovery: a tree with zero shell files must ERROR, got "
            "count=%d errors=%s" % (count, errors)
        )

    # 2. an unclassifiable file is READ, never skipped
    root = os.path.join(tmp, "disc-unclassifiable")
    os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
    with open(os.path.join(root, "scripts", "ok.sh"), "w") as fh:
        fh.write("#!/usr/bin/env bash\ntrue\n")
    for name in ("mystery.whatever", "no_shebang_no_extension"):
        with open(os.path.join(root, "scripts", name), "w") as fh:
            fh.write("GH_TOKEN='x'\necho \"$GH_TOKEN\"\n")
    findings, errors, count = scan_tree(root)
    if count != 3 or len(findings) != 2:
        failures.append(
            "discovery: a file with no shebang and an unrecognised extension "
            "must be READ, not skipped (scanned %d, findings %d, errors %s)"
            % (count, len(findings), errors)
        )

    # 3. an unrecognised shebang interpreter is READ, never skipped
    root = os.path.join(tmp, "disc-unknown-interp")
    os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
    with open(os.path.join(root, "scripts", "ok.sh"), "w") as fh:
        fh.write("#!/usr/bin/env bash\ntrue\n")
    with open(os.path.join(root, "scripts", "weird"), "w") as fh:
        fh.write("#!/usr/bin/env nosuchinterp\necho \"$GH_TOKEN\"\n")
    findings, errors, count = scan_tree(root)
    if count != 2 or not any("weird" in f.path for f in findings):
        failures.append(
            "discovery: an unrecognised shebang interpreter must be READ, "
            "not skipped (scanned %d, findings %s, errors %s)"
            % (count, [str(f) for f in findings], errors)
        )

    # 3b. a RECOGNISED non-shell interpreter is not read as shell
    root = os.path.join(tmp, "disc-known-nonshell")
    os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
    with open(os.path.join(root, "scripts", "ok.sh"), "w") as fh:
        fh.write("#!/usr/bin/env bash\ntrue\n")
    for interp in ("python3", "node", "tsx", "ruby", "perl"):
        with open(os.path.join(root, "scripts", "as_" + interp), "w") as fh:
            fh.write("#!/usr/bin/env %s\necho \"$GH_TOKEN\"\n" % interp)
    findings, errors, count = scan_tree(root)
    if count != 1 or findings:
        failures.append(
            "discovery: a recognised non-shell interpreter was read as shell "
            "(scanned %d, findings %s)" % (count, [str(f) for f in findings])
        )

    # 4. no scan roots at all
    root = os.path.join(tmp, "disc-no-roots")
    os.makedirs(root, exist_ok=True)
    _f, errors, count = scan_tree(root)
    if not errors:
        failures.append("discovery: a tree with no scan roots must ERROR")

    # 5. an unreadable file
    if os.geteuid() != 0:
        root = os.path.join(tmp, "disc-unreadable")
        os.makedirs(os.path.join(root, "scripts"), exist_ok=True)
        with open(os.path.join(root, "scripts", "ok.sh"), "w") as fh:
            fh.write("#!/usr/bin/env bash\ntrue\n")
        bad = os.path.join(root, "scripts", "locked.sh")
        with open(bad, "w") as fh:
            fh.write("#!/usr/bin/env bash\ntrue\n")
        os.chmod(bad, 0o000)
        try:
            _f, errors, _count = scan_tree(root)
            if not any("locked.sh" in e for e in errors):
                failures.append(
                    "discovery: an unreadable file must ERROR, errors=%s" % errors
                )
        finally:
            os.chmod(bad, 0o644)
    return failures


def _path_independence_case(tmp):
    """No path allow-lists: the verdict is a property of the LINE."""
    failures = []
    line = 'echo "$GH_TOKEN"\n'
    exempt = 'echo "$GH_TOKEN"  # TOKEN_OUTPUT_EXEMPT: a written reason\n'
    verdicts = {}
    for rel in (
        "scripts/op-preflight.sh",
        "scripts/ci/anything.sh",
        "tests/test_anything.sh",
        "scripts/deep/nested/other.sh",
    ):
        for label, body in (("plain", line), ("exempt", exempt)):
            root = os.path.join(tmp, "pi-%s-%s" % (label, rel.replace("/", "_")))
            path = os.path.join(root, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write("#!/usr/bin/env bash\nGH_TOKEN='x'\n" + body)
            findings, _errors, _count = scan_tree(root)
            verdicts.setdefault(label, set()).add(bool(findings))
    if verdicts.get("plain") != {True}:
        failures.append(
            "path independence: a plain emitter's verdict changed with its "
            "path (%s)" % verdicts.get("plain")
        )
    if verdicts.get("exempt") != {False}:
        failures.append(
            "path independence: an exempt line's verdict changed with its "
            "path (%s)" % verdicts.get("exempt")
        )
    return failures


def _residue_and_quoted_tmpdir_case():
    """Two successive runs leave nothing behind, and a quoted TMPDIR is inert.

    #1012 installed two `trap ... RETURN` handlers where the second replaced
    the first, so one temp file survived every `--scan`, and a `'` in TMPDIR
    injected into the trap string.  This rebuild holds no temp state in the
    scan path at all and drives its fixtures from a Python context manager, so
    the property is asserted directly rather than argued.
    """
    failures = []
    if os.environ.get("_TOKEN_OUTPUT_SELFTEST_INNER") == "1":
        return failures

    # The #1012 reproduction, asserted END TO END on the process exit code:
    # a tree whose ONLY file is an extensionless `#!/usr/bin/env -S bash -e`
    # script containing a live `echo "$GH_TOKEN"` must exit NON-ZERO.  #1012
    # exited 0 with `scanned 0 shell files` and PASS.
    with tempfile.TemporaryDirectory(prefix="token-output-envS.") as tree:
        os.makedirs(os.path.join(tree, "scripts"))
        only = os.path.join(tree, "scripts", "collect")
        with open(only, "w", encoding="utf-8") as fh:
            fh.write('#!/usr/bin/env -S bash -e\necho "$GH_TOKEN"\n')
        os.chmod(only, 0o755)
        proc = subprocess.run(
            [sys.executable, os.path.abspath(__file__), "--scan", tree],
            env=dict(os.environ, _TOKEN_OUTPUT_SELFTEST_INNER="1"),
            capture_output=True,
        )
        combined = (proc.stdout + proc.stderr).decode("utf-8", "replace")
        if proc.returncode == 0:
            failures.append(
                "env -S end to end: a tree whose only file is an "
                "extensionless `#!/usr/bin/env -S bash -e` script with a live "
                "`echo \"$GH_TOKEN\"` exited 0.  Output was:\n    %s"
                % combined.strip().replace("\n", "\n    ")
            )
        if "scanned 0 shell files" in combined and proc.returncode == 0:
            failures.append(
                "env -S end to end: `scanned 0 shell files` appeared on a "
                "passing run"
            )

    with tempfile.TemporaryDirectory(prefix="token-output-outer.") as outer:
        quoted = os.path.join(outer, "quo'te dir")
        os.makedirs(quoted, exist_ok=True)
        tree = os.path.join(outer, "tree")
        os.makedirs(os.path.join(tree, "scripts"), exist_ok=True)
        with open(os.path.join(tree, "scripts", "ok.sh"), "w") as fh:
            fh.write("#!/usr/bin/env bash\ntrue\n")
        env = dict(os.environ)
        env["TMPDIR"] = quoted
        env["_TOKEN_OUTPUT_SELFTEST_INNER"] = "1"
        for _ in range(2):
            proc = subprocess.run(
                [sys.executable, os.path.abspath(__file__), "--scan", tree],
                env=env,
                capture_output=True,
            )
            if proc.returncode != 0:
                failures.append(
                    "residue: --scan under a quoted TMPDIR exited %d: %s"
                    % (proc.returncode, proc.stderr.decode("utf-8", "replace")[:400])
                )
        proc = subprocess.run(
            [sys.executable, os.path.abspath(__file__), "--self-test"],
            env=env,
            capture_output=True,
        )
        if proc.returncode != 0:
            failures.append(
                "residue: --self-test under a quoted TMPDIR exited %d: %s"
                % (proc.returncode, proc.stderr.decode("utf-8", "replace")[-1500:])
            )
        leftover = sorted(os.listdir(quoted))
        if leftover:
            failures.append(
                "residue: %d file(s) left under TMPDIR after two runs: %s"
                % (len(leftover), leftover)
            )
    return failures



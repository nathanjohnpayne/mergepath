_POSITIONAL_RE = re.compile(r"\$(?:[1-9][0-9]*|[@*]|\{(?:[1-9][0-9]*|[@*])\})")


def _find_body(text, open_brace_idx):
    """Return the body text between matching braces, brace-depth counted over
    lexer state so a nested block or a brace inside a string cannot end it."""
    depth = 0
    i = open_brace_idx
    n = len(text)
    quotes = []
    while i < n:
        c = text[i]
        if quotes and quotes[-1] == "'":
            if c == "'":
                quotes.pop()
            i += 1
            continue
        if c == "\\":
            i += 2
            continue
        if c == "#" and not quotes and (i == 0 or text[i - 1] in _WORD_BREAK_BEFORE_COMMENT):
            eol = text.find("\n", i)
            i = n if eol == -1 else eol
            continue
        if c == "'":
            quotes.append("'")
            i += 1
            continue
        if c == '"':
            if quotes and quotes[-1] == '"':
                quotes.pop()
            else:
                quotes.append('"')
            i += 1
            continue
        if quotes:
            i += 1
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[open_brace_idx + 1 : i]
        i += 1
    return None


def discover_emitter_helpers(text):
    """Functions whose body writes one of their own positionals VERBATIM."""
    bodies = {}
    for m in re.finditer(
        r"(?m)^[ \t]*(?:function[ \t]+)?([A-Za-z_][A-Za-z0-9_:.-]*)[ \t]*"
        r"(?:\([ \t]*\))?[ \t]*\{",
        text,
    ):
        name = m.group(1)
        if name in RESERVED_WORDS:
            continue
        head = text[m.start() : m.end()]
        if "(" not in head and not head.lstrip().startswith("function"):
            continue
        body = _find_body(text, m.end() - 1)
        if body is not None:
            bodies[name] = body

    helpers = set()
    for _ in range(3):
        grew = False
        for name, body in bodies.items():
            if name in helpers:
                continue
            lx = Lexer(body)
            emits = False
            for ll in lx.logical:
                for seg in ll.segments:
                    kind = classify(seg, helpers)
                    if kind not in (EMIT,):
                        continue
                    for w in seg.words:
                        if _word_has_verbatim_positional(w):
                            emits = True
                            break
                    if emits:
                        break
                if emits:
                    break
            # a here-doc body inside the helper counts too
            if not emits:
                for hd in lx.heredocs:
                    if not hd.interpolating:
                        continue
                    cmd, _ = resolve_command(hd.owner)
                    if cmd in STDIN_ECHOERS or cmd in EMITTERS:
                        for _lno, raw in hd.body_lines:
                            if _POSITIONAL_RE.search(raw):
                                emits = True
                                break
                    if emits:
                        break
            if emits:
                helpers.add(name)
                grew = True
        if not grew:
            break
    return frozenset(helpers)


def _word_has_verbatim_positional(w):
    """True when the word expands a positional parameter's VALUE.

    Single-quoted text never expands, `${1:+set}` is a constant alternate and
    `${#1}` is a length -- a helper is entitled to use the same two redacted
    forms the check documents for callers.
    """
    i = 0
    n = len(w)
    while i < n:
        c = w[i]
        if c == "\\" and i + 1 < n:
            i += 2
            continue
        if c == "'":
            j = w.find("'", i + 1)
            i = n if j == -1 else j + 1
            continue
        if c == "$":
            if i + 1 < n and w[i + 1] == "{":
                j = i + 2
                if j < n and w[j] in "#!":
                    i += 2
                    continue
                m = re.match(r"([1-9][0-9]*|[@*])", w[j:])
                if m:
                    rest = w[j + m.end() : j + m.end() + 2]
                    if rest[:1] == "+" or rest[:2] == ":+":
                        i = j + m.end()
                        continue
                    return True
                i += 2
                continue
            m = re.match(r"([1-9][0-9]*|[@*])", w[i + 1 :])
            if m:
                return True
        i += 1
    return False



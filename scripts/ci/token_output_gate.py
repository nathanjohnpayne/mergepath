#!/usr/bin/env python3
r"""token_output_gate --- the enforcement half of #951 / #993 / #996.

Invoked through `scripts/ci/check_no_token_in_output`, the shell launcher
repo_lint wires; that file is three lines of dispatch and this one is the
gate.  Run it either way -- the launcher passes its arguments straight
through.

#951 found a live PAT printed in cleartext by a checker's own failure message.
#993 fixed the three sites it could find by grepping `scripts/` for five
variable names and executing every checker that matched under a sentinel
environment.  That is a point-in-time measurement: nothing mechanically stops
the next checker from reintroducing the shape.  This check is the mechanism.

THE RULE

    Under scripts/** and tests/**, a shell source line may not interpolate the
    VALUE of a known credential variable into an output command.

=========================================================================
WHY THIS FILE IS A REBUILD (#1015)
=========================================================================

The first attempt (#1012, closed and parked) decided "is this an output
command, and does this reference reach it" with a hand-written character walk,
and every review round found a NEW shell spelling the walk did not model --
five direct-form escapes were still live at close.  The list of shell spellings
is not a finite thing a reviewer can close by inspection, and 51 hand-written
fixtures could only assert what their author had already thought of.

So the deciding question is not "which constructs should the walk model?"  It
is "does this line put the value on a stream?", and that question is
EXECUTABLE.  This file carries both halves:

  * THE GATE is a STATIC scanner.  It runs in CI over a repository and never
    executes the source it scans.  Executing arbitrary repository source in CI
    would be unsafe, and its behaviour under a runner's environment would say
    nothing about its behaviour anywhere else.

  * THE ORACLE is for the TEST SUITE ONLY (`--self-test`).  For each construct
    in the corpus it writes a disposable fixture carrying an obviously fake
    sentinel in a credential-named variable, runs it under `bash` in a
    throwaway temp tree with a scrubbed environment, captures stdout AND
    stderr separately, and greps both for the sentinel.  That is GROUND TRUTH:
    the construct leaks or it does not, independent of anyone's opinion.  The
    fixtures are generated by this file; no repository source is ever executed.

    It is NOT independent of WHICH bash answers, which is why the interpreter
    is pinned and recorded rather than assumed.  An older bash rejects a
    construct it cannot parse and the oracle scores the rejection as CLEAN --
    on macOS's 3.2 that silently covers `${VAR@A}`, `${VAR@Q}`, `${VAR@P}`,
    `${VAR^^}`, `declare -n` and `|&`, every one of which puts the value on
    stdout under CI's 5.2.  `ORACLE_BASH_MIN` is the floor, the resolved path
    and version print on the summary line, and a run below the floor is
    refused with an environment error instead of producing a number that
    reads like ground truth and is not.  See the block above `run_oracle`.

    It is NOT independent of WHICH VALUE it samples either, and that one is
    still open.  Ground truth is established from a SINGLE sentinel, and that
    sentinel is LETTER-LEADING, so every verdict below was measured at ONE
    point in the value space rather than across credentials.  At least one
    construct's verdict is an artefact of that point: `echo $((GH_TOKEN))`
    reads CLEAN because a LETTER-LEADING operand is a NAME to bash, which
    finds it unset and evaluates it to `0`.  Hand the same line a
    DIGIT-LEADING NON-NUMERIC value and bash writes `9Zq7Xf2Lp: value too
    great for base (error token is "9Zq7Xf2Lp")` to STDERR -- the value,
    reproduced TWICE -- and `run_oracle` greps stderr.  Measured on this head:
    the oracle reports leaks=False under the shipped sentinel and leaks=True
    under a digit-leading one, while the SCANNER reads clean under both.  So
    the construct is an agreeing pair today and would be an UNDECLARED MISS
    the moment the sampled shape changed -- and it is not in `CORPUS` at all.
    (An ALL-DIGIT value reads clean again, because bash evaluates it as a
    number: one shape surfaces this, the other two do not, which is why the
    sweep is a sweep.)  So a construct that measures clean here may leak on a
    value shaped differently, and this corpus would not know.
    The sampled shape is derived from `SENTINEL` and PRINTS on the
    `--self-test` summary line beside the interpreter; that print is the
    record, the same way the registries are.  This is the `ORACLE_BASH_MIN`
    problem one axis over -- an unstated dependency of the measurement, on the
    VALUE instead of on the environment -- and unlike that one it is declared
    rather than closed: sweeping the corpus across letter-leading,
    digit-leading and all-digit sentinels is #1036.

    The suite then asserts the static scanner AGREES with the oracle on every
    construct.  A construct the oracle says leaks and the scanner calls clean
    is a FALSE NEGATIVE; a construct the oracle says is clean and the scanner
    flags is scanner conservatism.  Both must be DECLARED in `KNOWN_MISSES` or
    `KNOWN_BROADER` with a written reason, or the suite fails and prints the
    offending line together with the captured streams.  A declared entry that
    stops disagreeing also fails, so neither registry can quietly rot.

    This is the shape `check_doc_ownership` uses with markdown-it-py and the
    shape `markdown-target-parser-is-cmark-gfm` records: measure against the
    real implementation instead of reasoning about a specification.

=========================================================================
WHAT "KNOWN CREDENTIAL VARIABLE" MEANS (#996 design question 1)
=========================================================================

A CLOSED, EXPLICIT NAME LIST (`TOKEN_NAMES` below) -- not a heuristic over
names matching TOKEN / PAT / SECRET / KEY.  Carried unchanged from #1012,
where it survived five review rounds without a finding against it.

The list loses recall: a credential reached under some other name is invisible
to it.  That is the deliberate trade.  This check runs inside repo_lint, which
publishes the REQUIRED `lint` context, and repo_lint propagates to every
consumer repo -- so one false positive reds a required check across the fleet
with no break-glass.  A gate that is right about a smaller set beats one that
is broadly right and occasionally wrong.

The heuristic is also wrong on this tree, not just in principle.  A `*TOKEN*`
name match fires on `SUMMARY_ACK_TOKEN` / `ACK_TOKEN` (the
mergepath-summary-ack marker), `MERGEPATH_EXPECT_READ_GH_TOKEN` and
`STEP_NO_TOKEN` (flags), and `BOOTSTRAP_SKIP_AUTHOR_TOKEN` (a switch) -- none
of which hold credential material.  Every one would need an allow-list entry,
and that allow-list is then the thing nine repos have to get right.

Extending the list is a one-line edit here, in mergepath, which propagates to
every consumer with the rest of the scripts/ci kit.

=========================================================================
HOW LEGITIMATE EMITTERS ARE EXEMPTED (#996 design question 2)
=========================================================================

An INLINE PRAGMA, visible at the site, never a path allow-list:

    printf 'export OP_PREFLIGHT_REVIEWER_PAT=%q\n' "$OP_PREFLIGHT_REVIEWER_PAT"  # TOKEN_OUTPUT_EXEMPT: <reason>

The reason is MANDATORY -- a bare `TOKEN_OUTPUT_EXEMPT:` with nothing after it
still fails, the same hardening `NO_BARE_GH_WRITE_EXEMPT` got in #466.
`scripts/op-preflight.sh` is the canonical legitimate emitter: writing those
values to its cache IS its contract.

The marker counts ONLY inside a real shell comment -- a `#` that is unquoted,
unescaped, word-initial, and at parameter-expansion nesting depth zero.  #1012
was bypassable in two independent ways and both are re-established here as
properties with oracle-backed cases rather than inherited as patches:

  * `printf '%s %s\n' "$GH_TOKEN" 'TOKEN_OUTPUT_EXEMPT: text'` -- the marker is
    quoted DATA.  The command still runs and still writes the value.
  * `echo "$GH_TOKEN" ${UNSET:+ # TOKEN_OUTPUT_EXEMPT: bypass}` -- `${...}` is
    a parameter expansion, not a command context, so bash starts NO comment at
    that `#` and prints the value.

Both are corpus entries, both oracle-confirmed leaking, both flagged.

The pragma is a REVIEW MARKER, not a security boundary.  Anyone editing the
file can silence this check -- by adding the pragma, by renaming the variable,
by any of the indirections below.  What it buys is that every deliberate
emission is greppable and carries a written reason.

THERE ARE NO PATH ALLOW-LISTS ANYWHERE IN THIS CHECK.  The only path decision
it makes is which files are shell at all.  A corpus case pins that moving an
exempt line into a different file does not change its verdict.

=========================================================================
WHAT COUNTS AS OUTPUT, AND WHAT COUNTS AS CAPTURE
=========================================================================

  * `echo` / `printf` at a command position.  Command words are matched by
    BASENAME, so `/bin/echo` and `./1/echo` are the same emitter.  A shell
    reserved word is not the command -- the command follows it -- so
    `if echo "$PAT"; then` is the same emitter.  A leading redirection and an
    option-bearing wrapper (`env -i echo ...`) are stepped over -- its
    OPTIONS only, so a wrapper carrying an operand or an option ARGUMENT
    (`timeout 5 echo ...`, `nice -n 5 echo ...`) resolves to that word instead
    and the emitter behind it is missed.  An escaped command word (`\echo`) is
    the same emitter.  `printf -v NAME` is NOT output: bash assigns to a
    variable instead of writing to a stream -- but the `-v` test is
    position-blind, so a `-v` appearing as DATA after the format operand also
    reads as an assignment.  Both gaps are declared misses below.
  * An in-file message helper: a function whose body writes one of its own
    positional parameters VERBATIM through an emitter.  Both definition forms
    count, with the opening `{` on the DECLARATION line; bash also accepts it
    on the next line and helper discovery does not.  Body extraction is
    brace-depth counted over lexer state, so a nested block whose closing brace
    starts its own line does not end it early.  A helper is graded on what its
    body writes, not on where that write GOES, so a helper whose emitter feeds
    a pipe is treated as emitting -- declared conservatism below.
  * The body of an INTERPOLATING here-doc (unquoted delimiter) owned by `cat`,
    `tee` or an emitter.  ALL here-doc openers on a line are tracked, not just
    the first (#1014), and the owner is the command of the SEGMENT the opener
    appears in, so `true; cat <<EOF` attributes the body to `cat`.
  * The word of a here-STRING given to one of those same commands.

A PIPELINE IS NOT AN EMISSION; ITS CONSUMER DECIDES.  `printf '%s' "$PAT" |`
puts the value on the next command's STANDARD INPUT, which is the same act as
a here-doc body and a here-string -- and `grep -qF x <<< "$PAT"` is already
clean.  So the walk follows the pipe and asks what the consumer does with its
stdin: `cat`/`tee` write it (flagged, and a `cat | cat | grep -q` chain is
followed hop by hop), an unresolvable or `eval` consumer fails closed, and
anything else is the same unmodelled question as a value handed to a command
as an ARGUMENT.  This is what makes `printf '%s' "$PAT" | gh auth login
--with-token` and `echo "$PAT" | docker login --password-stdin` -- the
canonical secure hand-off, and gh's and docker's own documented interface --
legal without a pragma.  Only a redirection that moves fd 1 escapes the pipe
(`>&2`, `>file`); `2>/dev/null` does not.  A trailing `|` continues the
command list onto the next physical line, exactly as a trailing `\` does.

CAPTURE IS NOT EMISSION.  In `_v=$(printf '%s' "$GH_TOKEN")` the value goes
into a variable.  The shield is conditional, because #1012 measured the escape:
`_v=$(printf '%s' "$GH_TOKEN" >&2)` redirects past the capture and reaches the
terminal.  So a captured emitter counts as capture only when the emitting
segment carries NO redirection at all; any redirection inside the substitution
is flagged.  A subshell or brace group is not a capture: `( echo "$PAT" )`
is flagged.

REDACTION IS NOT EMISSION.  `${#VAR}` is a length and `${VAR:+set}` is a
constant alternate; neither is a value reference, so both are legal with no
pragma -- they are the #993 remediation and adopting it never trips the gate.
`${VAR:+$VAR}` carries its own expansion and the inner reference is flagged on
its own.  A helper that derives a length or a class and prints that is
therefore not a message helper, so `key_state "$PAT"` stays legal.

=========================================================================
WHAT THIS CHECK DOES NOT CATCH
=========================================================================

Re-derived from what the harness ACTUALLY shows, not from what the author
believes.  Every entry below that names a shell CONSTRUCT is a live corpus case
whose disagreement with the oracle is declared in `KNOWN_MISSES`, and
`--self-test` PRINTS that registry on every run, so this prose cannot drift
away from the measurement -- if the two ever disagree, the printed list is the
true one.  Exactly two entries are NOT constructs and carry no corpus case, and
both say so where they appear: what the shell emits on its own (`set -x`, core
dumps), and files this check does not read at all.  Read the other direction
too, and it holds with one exception: every `KNOWN_MISSES` entry appears below
except `pragma-honoured`, which is not a limit -- it is the deliberate
exemption described above, a declared "miss" because the line really does emit
and the scanner really does stay silent, on purpose.

READ IT AS THE MEASURED SAMPLE IT IS: an absence from this list is NOT
coverage.  The scanner is a source-text approximation; the oracle is the only
thing here that knows the truth, and it only knows it about constructs someone
put in the corpus -- and only under the one sentinel shape that corpus samples
(#1036, and the oracle paragraph above).

The list below mixes TWO KINDS of gap and says which is which.  Most of it is
the DESIGN LIMIT: this is a single-hop source-text scanner over one logical line
at a time, with no dataflow, no cross-file analysis, and no knowledge of what a
variable holds at runtime, so indirection, external commands, interpreters and
unscanned files are permanently out of reach.  Four bullets are marked (#1035)
instead: those are `resolve_command` / `classify` mis-deciding what a segment
RUNS, a repairable seam with an open issue, not a property of the design.  It
does not catch:

  * A token copied into a differently-named variable and then printed
    (`pat=$OP_PREFLIGHT_AUTHOR_PAT; echo "$pat"`), or reached through a
    function return, a `read`, a `printf -v`, a loop variable, or `$(op read
    ...)`.
  * A token written to a log or temp file that some later line prints
    (`cat "$LOG"`).  It DOES catch the line that puts the value into the log,
    when that line names the variable; it cannot connect that line to the `cat`
    that prints it.
  * `set -x` traces, core dumps, or anything the shell emits on its own.  Not
    a construct in a line, so there is no corpus case behind this one -- it is
    a statement about the shell, and the harness has nothing to say about it.
  * (#1035) A SHELL-STATE DUMPER on a segment that names no credential
    variable.  The boundary here is the REFERENCE, not the command word, and
    the earlier wording of this bullet had it the other way round.  This scanner asks
    "does this reference reach a stream?", so `classify()` -- which is where
    `env`/`printenv`/`set`/`compgen` are known to be dumpers at all -- is
    consulted only for a segment carrying a `$`-reference.  Measured, on this
    head: `set`, `set -o posix; set`, `declare -p GH_TOKEN` and
    `export GH_TOKEN; env` each put the value on a stream and each reads
    CLEAN, and all four are live corpus cases in `KNOWN_MISSES`.  What IS
    caught is `FOO="$GH_TOKEN" env` and `env FOO="$GH_TOKEN"` -- both corpus
    cases, both measured true positives -- and they are caught because the
    segment carries a reference, which is what makes the walk run and then ask
    whether the command dumps the environment it was handed.  A dumper reached
    through a variable is not caught either, because nothing in the source text
    says what it is.
  * (#1035) A WRAPPER whose real command word sits behind an operand or an
    option ARGUMENT: `timeout 5 echo "$PAT"` and `nice -n 5 echo "$PAT"` both
    resolve to `5` and read clean.  Wrapper OPTIONS are stepped over; wrapper
    operands are not parsed.
  * (#1035) `printf '%s\n' -v "$PAT"`, where `-v` is DATA after the format
    operand.  The `printf -v` assignment test scans every word rather than only
    option position, so the segment reads as an assignment, not an emission.
  * (#1035) A message helper whose opening `{` starts the line AFTER the
    declaration (`log()` then `{ echo "$1"; }`).  The one-line spelling of the
    same helper is found and flagged, so this is a spelling gap in discovery.
  * A token handed to an EXTERNAL command -- as an ARGUMENT
    (`curl -H "Authorization: Bearer $CF_API_TOKEN"`), on a HERE-STRING
    (`grep . <<< "$PAT"`), or through a PIPE (`printf '%s' "$PAT" | grep .`).
    This check knows what `echo`, `printf`, `cat` and `tee` do with what they
    are handed and does not pretend to know what anything else does.
    Deliberate: flagging every external command that receives a credential
    would red a required fleet-wide check on the ordinary way credentials are
    passed.  All three spellings carry the same verdict on purpose -- flagging
    only the pipe one made the gate contradict itself, and it reds the
    canonical `--with-token` / `--password-stdin` hand-off.
  * An in-file helper that writes its STANDARD INPUT rather than one of its
    positional parameters (`relay() { cat; }` behind a pipe).  Helper
    discovery models parameters; nothing at the call site says what a helper
    reads.
  * A token reaching an interpreter that then prints it (`bash -c ...`,
    `python3 -c ...`, `awk -v ...`, a `bash <<EOF` here-doc).
  * Any file this check does not scan: non-shell files, and everything outside
    scripts/** and tests/**.  Also not a construct: the file-selection axis
    pins WHICH files are read, not what a leak inside an unread one looks like,
    so there is no corpus case behind this one either.

CONSERVATISM RUNS THE OTHER WAY IN A SHORT LIST, also measured, and
`KNOWN_BROADER` -- printed on every `--self-test` run -- is the authoritative
copy of it; this prose is a description of that registry, not a second source:

  * An emitter redirected to a FILE (`printf '%s\n' "$PAT" > log`) puts
    nothing on a stream, and the gate flags it anyway.  That write is the
    FIRST HOP of the check_resolve_pr_threads leak #993 fixed, and the gate is
    built so that hop stays visible.
  * A pipeline whose consumer is NOT a simple command -- `| { read -r v; }`,
    `| ( read -r v )`, and `|&`, whose consumer segment is recorded empty.
    Which command inside a group reads the pipe is a dataflow question a
    single-line source-text scanner cannot answer, so the consumer counts as
    unresolved and the case fails CLOSED.  The named-command form of the same
    idiom (`| gh auth login --with-token`) is clean.
  * (#1035) A MESSAGE HELPER whose emitter feeds a pipe:
    `login() { printf %s "$1" | gh auth login --with-token; }` plus
    `login "$PAT"`.  Helper discovery grades what the body writes without
    asking where that write goes, so it does not run the pipeline-consumer
    analysis the direct form gets.  Nothing reaches a stream and the gate reds.
  * (#1035) An INPUT PROCESS SUBSTITUTION: `grep -qF x <(printf '%s'
    "$PAT")`.  Every `<(...)` body is graded as a standalone output path with
    no model of what consumes the fd, so this reds while emitting nothing.  `cat <(...)` really
    does leak and is flagged by the same undiscriminating rule, which is why
    the two are not currently told apart.

The last two are LIVE false positives on a check that publishes the required
`lint` context, not conservatism anyone chose; both are declared in
`KNOWN_BROADER` and both are #1035's to repair.  Neither fires on any of the
ten trees measured today.  Until the repair lands, A FALSE POSITIVE IS
ESCAPABLE AT THE SITE: add `# TOKEN_OUTPUT_EXEMPT: <reason>` to the line, with
a reason (the reason is mandatory).  That is the same inline pragma a
legitimate emitter uses, it needs no change to this file and no path
allow-list, and it leaves the decision greppable.

STATED PLAINLY, because #993's lesson was that an unstated limit reads as a
guarantee: NONE of the three leaks #993 fixed would have been caught by this
gate at their original sites.  All three reached the token under another name
or through a file.  This gate stops the DIRECT form from coming back; it is
not a proof that no credential can reach a stream.

And the recall claim is bounded by the CORPUS and by the SENTINEL, not by an
argument.  What the harness demonstrates is that on ~393 constructs --
generated across line spellings, file selection, pipeline consumers and
legal-but-unusual precision shapes, each measured against ONE letter-leading
sentinel value -- the scanner and bash agree except for the declared entries.
The run prints the exact count, the interpreter AND the sentinel shape that
produced it, and both registries; that print is the number of record, not this
sentence.  A construct nobody wrote into the corpus is not covered by the
statement at all, and neither is a value shape nobody sampled (#1036).  Adding
a construct is a three-line edit to `CORPUS`, and the oracle decides it --
under an interpreter that can evaluate it, which is what `ORACLE_BASH_MIN`
is for.

Related and equally out of reach (#1021): `scripts/op-preflight.sh` writing
export lines carrying live PAT values to ITS OWN stdout is a CALLER-side
problem.  That emission is the script's contract when its output is consumed by
`eval`, and a leak when a caller lets it reach a transcript.  No source-text
rule over `scripts/**` can separate the two, because the difference is in the
caller, not in the line.  The three op-preflight emitters carry
`TOKEN_OUTPUT_EXEMPT` pragmas so the decision is greppable; that is all a
source-text gate can do here.

=========================================================================
FILE DISCOVERY FAILS CLOSED
=========================================================================

#1012 shipped a discovery that failed OPEN: `#!/usr/bin/env -S bash -e` on an
extensionless script reduced the interpreter to `-S`, so the file was not
recognised as shell at all and a tree whose only file was such a script,
containing a live `echo "$GH_TOKEN"`, reported `scanned 0 shell files` and
PASS.  That is the #951 shape -- a green gate saying nothing was wrong --
reproduced inside the gate built to stop #951.

Here the property asserted is: A FILE BASH WILL EXECUTE IS A FILE THE GATE
READS, and every branch that cannot establish it is FATAL, not skipped:

  * A shebang is resolved through `env`, including `-S` / `--split-string=`,
    `-i`, `-u NAME`, `-C DIR` and `NAME=VALUE` assignments.
  * A file whose interpreter or extension classifies as neither shell nor
    known-non-shell is an ERROR, not a skip.
  * An unreadable path, or a traversal failure, is an ERROR.
  * A scan selecting ZERO shell files is an ERROR.  `scanned 0` can never be
    an advisory count on a PASS line again; a corpus case asserts it directly.

Usage:
    check_no_token_in_output              # self-test, then scan this repo
    check_no_token_in_output --self-test  # oracle-differential suite only
    check_no_token_in_output --scan [DIR] # scan only (default: this repo)

`--scan DIR` is also how the fleet measurement is taken: pointing it at
mergepath plus the nine consumer checkouts is the ten-tree hit-set comparison
#1015 asks for.  It is deliberately NOT a CI step -- CI has one tree, and a
step that cloned nine repositories to lint one would be a different kind of
gate.  The numbers from that run belong in the PR body, where a reviewer can
see them.

Exit codes: 0 pass, 1 findings or a failing case, 2 usage/environment error.
"""


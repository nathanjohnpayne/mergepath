# ==========================================================================
# Lexer
# ==========================================================================
#
# One pass over the file produces, for every character: whether a `$` there
# would expand, whether it sits in a comment, and which command SEGMENT owns
# it.  Everything downstream reads off that; there is no second walk with its
# own idea of quoting, which is the divergence #1012's comment-finder and
# continuation-finder produced.

class Segment:
    __slots__ = (
        "sid", "parent", "parent_is_capture", "words", "line",
        "_cmd", "_resolved",
    )

    def __init__(self, sid, parent, parent_is_capture, line):
        self.sid = sid
        self.parent = parent
        self.parent_is_capture = parent_is_capture
        self.words = []  # list of (text, is_quoted_start)
        self.line = line
        self._cmd = None
        self._resolved = False


class Ref:
    __slots__ = ("name", "line", "seg", "heredoc_owner", "in_assign_prefix")

    def __init__(self, name, line, seg, in_assign_prefix=False):
        self.name = name
        self.line = line
        self.seg = seg
        self.heredoc_owner = None
        self.in_assign_prefix = in_assign_prefix


class HereDoc:
    __slots__ = ("delim", "interpolating", "strip_tabs", "owner", "body_lines")

    def __init__(self, delim, interpolating, strip_tabs, owner):
        self.delim = delim
        self.interpolating = interpolating
        self.strip_tabs = strip_tabs
        self.owner = owner
        self.body_lines = []


class LogicalLine:
    __slots__ = ("first_line", "segments", "refs", "pragma_reasons", "pragma_bare")

    def __init__(self, first_line):
        self.first_line = first_line
        self.segments = []
        self.refs = []
        self.pragma_reasons = []
        self.pragma_bare = False


_WORD_BREAK_BEFORE_COMMENT = set(" \t\n;&|()")
_IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_ASSIGN_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\[[^]]*\])?\+?=")
_REDIR_RE = re.compile(r"^\{?[A-Za-z0-9_]*\}?(&>>|&>|>>|>\||>&|<&|<>|<|>)")
_PRAGMA_RE = re.compile(r"(?<![A-Za-z0-9_])" + PRAGMA + r":[ \t]*(\S.*)?$")


class Lexer:
    """Segment-aware shell lexer.  Never executes anything it reads."""

    def __init__(self, text):
        self.text = text
        self.logical = []
        self.heredocs = []
        self.func_defs = []  # (name, body_start_index, body_end_index)
        self._sid = 0
        self._run()

    # -- helpers ---------------------------------------------------------
    def _new_segment(self, parent, capture, line):
        self._sid += 1
        seg = Segment(self._sid, parent, capture, line)
        return seg

    def _run(self):
        text = self.text
        n = len(text)
        i = 0
        line = 1

        cur_ll = LogicalLine(1)
        self.logical.append(cur_ll)

        # Level stack.  Each level: dict(seg=..., parent=..., capture=bool,
        # close=str, word=[chars], word_started=bool)
        top = {
            "seg": self._new_segment(None, False, line),
            "capture": False,
            "kind": "top",
            "word": [],
        }
        cur_ll.segments.append(top["seg"])
        levels = [top]

        # Quote stack, innermost last.  Entries: "'", '"', "${", "$((".
        #
        # Quoting is PER LEVEL: inside `$( ... )` bash restarts it, so the
        # inner `"` of `"$(f "${VAR:-}")"` OPENS a string rather than closing
        # the outer one.  One shared stack reads that inner quote as a close,
        # then swallows the `)` that ends the substitution, and everything
        # after it lands in one runaway segment whose command word is
        # unresolvable -- measured as 14 false positives over this tree.
        # The stack is saved on the level being left and restored on return.
        quotes = []

        pending_heredocs = []  # HereDoc objects awaiting a body
        in_heredoc = None

        case_depth = [0]

        def cur_level():
            return levels[-1]

        def expanding():
            return "'" not in quotes

        def finish_word():
            lv = cur_level()
            if lv["word"]:
                w = "".join(lv["word"])
                lv["seg"].words.append(w)
                lv["word"] = []
                if w == "case":
                    case_depth[0] += 1
                elif w == "esac" and case_depth[0] > 0:
                    case_depth[0] -= 1

        def in_assign_prefix():
            """True when the reference sits in an env-assignment PREFIX.

            `GH_TOKEN="$OP_PREFLIGHT_REVIEWER_PAT" "$cmd" ...` puts the value
            in the child's ENVIRONMENT, not on a stream, and it is the fleet's
            standard way of handing a credential to a command whose word is
            itself a variable.  The prefix only counts while no command word
            has been seen yet, so `echo x=$GH_TOKEN` is not mistaken for one.
            """
            lv = cur_level()
            for w in lv["seg"].words:
                if w in RESERVED_WORDS:
                    continue  # `if ! GH_TOKEN="$PAT" "$checker" ...`
                if not _ASSIGN_RE.match(w):
                    return False
            return bool(_ASSIGN_RE.match("".join(lv["word"])))

        def start_segment():
            finish_word()
            lv = cur_level()
            seg = self._new_segment(lv["seg"].parent, lv["capture"], line)
            seg.parent = lv["seg"].parent
            lv["seg"] = seg
            cur_ll.segments.append(seg)

        def end_logical_line(next_line):
            nonlocal cur_ll
            finish_word()
            cur_ll = LogicalLine(next_line)
            self.logical.append(cur_ll)
            lv = levels[0]
            seg = self._new_segment(None, False, next_line)
            lv["seg"] = seg
            cur_ll.segments.append(seg)

        while i < n:
            c = text[i]

            # ---- inside a here-doc body ----
            if in_heredoc is not None:
                eol = text.find("\n", i)
                if eol == -1:
                    eol = n
                raw = text[i:eol]
                probe = raw.lstrip("\t") if in_heredoc.strip_tabs else raw
                if probe == in_heredoc.delim:
                    in_heredoc = None
                else:
                    in_heredoc.body_lines.append((line, raw))
                    if in_heredoc.interpolating:
                        for m in _iter_refs(raw):
                            r = Ref(m, line, in_heredoc.owner)
                            r.heredoc_owner = in_heredoc.owner
                            cur_ll.refs.append(r)
                i = eol + 1
                line += 1
                if in_heredoc is None:
                    if pending_heredocs:
                        in_heredoc = pending_heredocs.pop(0)
                    else:
                        end_logical_line(line)
                continue

            # ---- single quotes ----
            if quotes and quotes[-1] == "'":
                if c == "'":
                    quotes.pop()
                elif c == "\n":
                    line += 1
                cur_level()["word"].append(c)
                i += 1
                continue

            # ---- backslash escape (not inside single quotes) ----
            if c == "\\":
                if i + 1 < n and text[i + 1] == "\n":
                    # Line continuation: the logical line continues.
                    i += 2
                    line += 1
                    continue
                if i + 1 < n:
                    cur_level()["word"].append(c)
                    cur_level()["word"].append(text[i + 1])
                    if text[i + 1] == "\n":
                        line += 1
                    i += 2
                    continue
                cur_level()["word"].append(c)
                i += 1
                continue

            # ---- comment: only at word-initial position, unquoted, depth 0 ----
            if (
                c == "#"
                and not quotes
                and not cur_level()["word"]
                and (i == 0 or text[i - 1] in _WORD_BREAK_BEFORE_COMMENT)
            ):
                eol = text.find("\n", i)
                if eol == -1:
                    eol = n
                comment = text[i:eol]
                m = _PRAGMA_RE.search(comment)
                if m:
                    reason = (m.group(1) or "").strip()
                    if reason:
                        cur_ll.pragma_reasons.append(reason)
                    else:
                        cur_ll.pragma_bare = True
                i = eol
                continue

            # ---- expansions and quotes ----
            if c == "$" and i + 1 < n:
                nxt = text[i + 1]
                if nxt == "(" and i + 2 < n and text[i + 2] == "(":
                    quotes.append("$((")
                    cur_level()["word"].append("$((")
                    i += 3
                    continue
                if nxt == "(":
                    # command substitution: a capturing level
                    parent_seg = cur_level()["seg"]
                    seg = self._new_segment(parent_seg, True, line)
                    cur_ll.segments.append(seg)
                    levels.append(
                        {
                            "seg": seg,
                            "capture": True,
                            "kind": "cmdsub",
                            "word": [],
                            "saved_quotes": quotes,
                        }
                    )
                    quotes = []
                    i += 2
                    continue
                if nxt == "{":
                    quotes.append("${")
                    cur_level()["word"].append("${")
                    # `${NAME...}`: decide here whether the OUTER name is a
                    # value reference.  `${#NAME}` is a length and `${!NAME}`
                    # an indirection; `${NAME:+WORD}` / `${NAME+WORD}` is a
                    # constant alternate.  Anything nested inside the braces
                    # is found by this same loop on its own `$`.
                    j = i + 2
                    if j < n and text[j] not in "#!" and expanding():
                        m = _IDENT_RE.match(text, j)
                        if m and m.group(0) in TOKEN_NAME_SET:
                            op = text[m.end() : m.end() + 2]
                            if not (op[:2] == ":+" or op[:1] == "+"):
                                cur_ll.refs.append(
                                    Ref(
                                        m.group(0),
                                        line,
                                        cur_level()["seg"],
                                        in_assign_prefix(),
                                    )
                                )
                    i += 2
                    continue
                # a plain variable reference
                if expanding():
                    m = _IDENT_RE.match(text, i + 1)
                    if m and m.group(0) in TOKEN_NAME_SET:
                        cur_ll.refs.append(
                            Ref(
                                m.group(0),
                                line,
                                cur_level()["seg"],
                                in_assign_prefix(),
                            )
                        )
                cur_level()["word"].append(c)
                i += 1
                continue

            if c == "}" and quotes and quotes[-1] == "${":
                quotes.pop()
                cur_level()["word"].append(c)
                i += 1
                continue

            if c == ")" and quotes and quotes[-1] == "$((":
                if i + 1 < n and text[i + 1] == ")":
                    quotes.pop()
                    cur_level()["word"].append("))")
                    i += 2
                    continue

            if c == "'" and (not quotes or quotes[-1] in ("${", "$((")):
                quotes.append("'")
                cur_level()["word"].append(c)
                i += 1
                continue

            if c == '"':
                if quotes and quotes[-1] == '"':
                    quotes.pop()
                else:
                    quotes.append('"')
                cur_level()["word"].append(c)
                i += 1
                continue

            # Inside `${...}` or `$((...))` or `"..."`: track a reference by
            # name but do not treat operators as structure.
            if quotes:
                if c == "\n":
                    line += 1
                cur_level()["word"].append(c)
                i += 1
                continue

            if c == "`":
                # Backticks: treat like a capturing command substitution.
                close = text.find("`", i + 1)
                if close == -1:
                    close = n
                inner = text[i + 1 : close]
                parent_seg = cur_level()["seg"]
                sub = Lexer(inner)
                for ll in sub.logical:
                    for r in ll.refs:
                        rr = Ref(r.name, line, r.seg)
                        rr.seg.parent = parent_seg
                        rr.seg.parent_is_capture = True
                        cur_ll.refs.append(rr)
                    cur_ll.segments.extend(ll.segments)
                line += inner.count("\n")
                cur_level()["word"].append("`sub`")
                i = close + 1
                continue

            # ---- here-doc / here-string openers ----
            if c == "<" and i + 1 < n and text[i + 1] == "<":
                if i + 2 < n and text[i + 2] == "<":
                    # here-string: the following word belongs to this segment
                    cur_level()["seg"].words.append("<<<")
                    i += 3
                    continue
                j = i + 2
                strip_tabs = False
                if j < n and text[j] == "-":
                    strip_tabs = True
                    j += 1
                while j < n and text[j] in " \t":
                    j += 1
                delim_chars = []
                interpolating = True
                while j < n:
                    ch = text[j]
                    if ch in "'\"":
                        interpolating = False
                        q = ch
                        j += 1
                        while j < n and text[j] != q:
                            delim_chars.append(text[j])
                            j += 1
                        j += 1
                        continue
                    if ch == "\\":
                        interpolating = False
                        j += 1
                        if j < n:
                            delim_chars.append(text[j])
                            j += 1
                        continue
                    if ch.isalnum() or ch in "_-.+/":
                        delim_chars.append(ch)
                        j += 1
                        continue
                    break
                delim = "".join(delim_chars)
                if delim:
                    hd = HereDoc(delim, interpolating, strip_tabs, cur_level()["seg"])
                    pending_heredocs.append(hd)
                    self.heredocs.append(hd)
                    cur_level()["seg"].words.append("<<")
                i = j
                continue

            # ---- structure ----
            if c == "\n":
                finish_word()
                line += 1
                i += 1
                if pending_heredocs:
                    in_heredoc = pending_heredocs.pop(0)
                    continue
                if len(levels) > 1:
                    # newline inside `$( ... )` is a segment break, not a
                    # logical-line break
                    start_segment()
                    continue
                end_logical_line(line)
                continue

            if c in " \t":
                finish_word()
                i += 1
                continue

            if c == ";":
                start_segment()
                i += 1
                continue

            # ---- redirection operators ----
            # Consumed WHOLESALE, because `>&2` and `&>file` carry a `&` and
            # `>|` a `|`.  Reading either as a list operator splits the logical
            # command in half and the emitter behind it is never seen -- the
            # `>&2 echo "$PAT"` and `$(... >&2)` escapes measured on #1012.
            if c in "<>" and text[i + 1 : i + 2] == "(":
                # process substitution: a NON-capturing level, so the emitter
                # inside is judged on its own merits
                parent_seg = cur_level()["seg"]
                seg = self._new_segment(parent_seg, False, line)
                cur_ll.segments.append(seg)
                levels.append(
                    {
                        "seg": seg,
                        "capture": False,
                        "kind": "procsub",
                        "word": [],
                        "saved_quotes": quotes,
                    }
                )
                quotes = []
                i += 2
                continue

            if c in "<>":
                j = i + 1
                if c == ">" and text[j : j + 1] in (">", "|"):
                    j += 1
                elif text[j : j + 1] == "&":
                    j += 1
                    while j < n and text[j].isdigit():
                        j += 1
                    if text[j : j + 1] == "-":
                        j += 1
                elif c == "<" and text[j : j + 1] == ">":
                    j += 1
                cur_level()["word"].append(text[i:j])
                i = j
                continue

            if c == "&":
                if text[i + 1 : i + 2] == "&":
                    start_segment()
                    i += 2
                    continue
                if text[i + 1 : i + 2] == ">":
                    j = i + 2
                    if text[j : j + 1] == ">":
                        j += 1
                    cur_level()["word"].append(text[i:j])
                    i = j
                    continue
                start_segment()
                i += 1
                continue

            if c == "|":
                if i + 1 < n and text[i + 1] == "|":
                    start_segment()
                    i += 2
                    continue
                start_segment()
                i += 1
                continue

            if c == "(":
                word_so_far = "".join(cur_level()["word"])
                if word_so_far.endswith("="):
                    # An ARRAY ASSIGNMENT.  `args=(echo "$PAT")` stores two
                    # strings and writes nothing; reading the `(` as a command
                    # position is how #1012 round 4 flagged it.  The whole
                    # parenthesised list belongs to the assignment word.
                    j = _skip_balanced_parens(text, i)
                    cur_level()["word"].append(text[i:j].replace("\n", " "))
                    line += text[i:j].count("\n")
                    i = j
                    continue
                if not word_so_far:
                    # subshell / case-pattern parens: a NON-capturing level
                    parent_seg = cur_level()["seg"]
                    seg = self._new_segment(parent_seg, False, line)
                    cur_ll.segments.append(seg)
                    levels.append(
                        {
                            "seg": seg,
                            "capture": False,
                            "kind": "subshell",
                            "word": [],
                            "saved_quotes": quotes,
                        }
                    )
                    quotes = []
                    i += 1
                    continue
                cur_level()["word"].append(c)
                i += 1
                continue

            if c == ")":
                if len(levels) > 1:
                    finish_word()
                    kind = levels[-1]["kind"]
                    quotes = levels[-1]["saved_quotes"]
                    levels.pop()
                    if kind == "cmdsub":
                        cur_level()["word"].append("$()")
                    elif case_depth[0] > 0:
                        # `case x in (pat) cmd ;;` -- the pattern's `)` ends
                        # the pattern, and the command after it is its own
                        # segment.
                        start_segment()
                    i += 1
                    continue
                if case_depth[0] > 0:
                    # `case x in pat) cmd ;;` -- an unmatched `)` inside a
                    # case body is a pattern terminator, never part of the
                    # command, so the emitter after it heads its own segment.
                    start_segment()
                    i += 1
                    continue
                cur_level()["word"].append(c)
                i += 1
                continue

            if c == "{" and not cur_level()["word"]:
                cur_level()["seg"].words.append("{")
                start_segment()
                i += 1
                continue

            if c == "}" and not cur_level()["word"]:
                start_segment()
                i += 1
                continue

            cur_level()["word"].append(c)
            i += 1

        finish_word()


def _skip_balanced_parens(text, start):
    """Return the index just past the `)` matching the `(` at `start`."""
    depth = 0
    i = start
    n = len(text)
    quotes = []
    while i < n:
        c = text[i]
        if quotes and quotes[-1] == "'":
            if c == "'":
                quotes.pop()
            i += 1
            continue
        if c == "\\":
            i += 2
            continue
        if c == "'":
            quotes.append("'")
            i += 1
            continue
        if c == '"':
            if quotes and quotes[-1] == '"':
                quotes.pop()
            else:
                quotes.append('"')
            i += 1
            continue
        if quotes:
            i += 1
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return n


def _iter_refs(s):
    """Yield credential names referenced for their VALUE in a raw string."""
    out = []
    i = 0
    n = len(s)
    while i < n:
        ch = s[i]
        if ch == "\\" and i + 1 < n:
            i += 2
            continue
        if ch == "$":
            if i + 1 < n and s[i + 1] == "{":
                j = i + 2
                if j < n and s[j] in "#!":
                    # ${#NAME} is a length; ${!NAME} is an indirection.
                    i += 1
                    continue
                m = _IDENT_RE.match(s, j)
                if m and m.group(0) in TOKEN_NAME_SET:
                    op = s[m.end() : m.end() + 2]
                    if op.startswith(":+") or op.startswith("+}") or (
                        op[:1] == "+"
                    ):
                        # constant alternate: not a value reference.  A nested
                        # expansion inside the alternate is found on its own.
                        i = m.end()
                        continue
                    out.append(m.group(0))
                i = j
                continue
            m = _IDENT_RE.match(s, i + 1)
            if m and m.group(0) in TOKEN_NAME_SET:
                out.append(m.group(0))
                i = m.end()
                continue
        i += 1
    return out



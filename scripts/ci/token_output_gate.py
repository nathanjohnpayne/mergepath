def main(argv):
    repo_root = os.path.abspath(
        os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    )
    mode = "all"
    target = repo_root
    args = argv[1:]
    if args and args[0] == "--self-test":
        mode = "self-test"
        args = args[1:]
    elif args and args[0] == "--scan":
        mode = "scan"
        args = args[1:]
        if args:
            target = os.path.abspath(args[0])
            args = args[1:]
    if args:
        print(
            "check_no_token_in_output: unexpected argument %r\n%s"
            % (args[0], "usage: check_no_token_in_output [--self-test | --scan [DIR]]"),
            file=sys.stderr,
        )
        return 2

    if mode in ("all", "self-test"):
        bash_path, bash_text, bash_ver = oracle_bash()
        if bash_path is None:
            print(
                "check_no_token_in_output: bash is required -- the self-test's "
                "oracle runs fixtures under bash and there is no substitute "
                "for it (#1015)",
                file=sys.stderr,
            )
            return 2
        if bash_ver is None or bash_ver < ORACLE_BASH_MIN:
            print(
                "check_no_token_in_output: the oracle needs bash >= %d.%d and "
                "PATH resolves to %s (%s).\n"
                "An older bash REJECTS constructs it cannot parse -- "
                "${VAR@A}, ${VAR@Q}, ${VAR@P}, ${VAR^^}, `declare -n`, `|&` "
                "-- and the oracle records the rejection as CLEAN, so the "
                "differential under-reports leaks that are real in CI.  It is "
                "refused rather than run, because a number measured that way "
                "reads as ground truth and is not.\n"
                "macOS ships bash 3.2 as /bin/bash; install a current one "
                "(`brew install bash`) and put it ahead on PATH.  Scanning "
                "does not need it: `check_no_token_in_output --scan [DIR]` "
                "runs the gate with no oracle."
                % (ORACLE_BASH_MIN[0], ORACLE_BASH_MIN[1], bash_path, bash_text),
                file=sys.stderr,
            )
            return 2
        rc = self_test()
        if rc != 0:
            print("check_no_token_in_output: FAIL (self-test)", file=sys.stderr)
            return 1
        if mode == "self-test":
            print("check_no_token_in_output: PASS (self-test)")
            return 0

    findings, errors, count = scan_tree(target)
    for e in errors:
        print("check_no_token_in_output: ERROR: %s" % e, file=sys.stderr)
    for f in findings:
        print("check_no_token_in_output: %s" % f, file=sys.stderr)
    if errors or findings:
        print(
            "check_no_token_in_output: FAIL (%d finding(s), %d discovery "
            "error(s) over %d shell files)" % (len(findings), len(errors), count),
            file=sys.stderr,
        )
        if findings:
            print(
                "check_no_token_in_output: a deliberate emitter carries an "
                "inline `# %s: <reason>` comment at the site; the reason is "
                "mandatory." % PRAGMA,
                file=sys.stderr,
            )
        return 1
    print("check_no_token_in_output: PASS (%d shell files scanned)" % count)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

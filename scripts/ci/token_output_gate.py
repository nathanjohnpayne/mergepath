# token should I use" flag) are deliberately absent -- see the header.
#
# The invariant reads "denotes credential material", not "is live here",
# because the first is a property of the NAME and the second is a property of
# today's integrations.  An earlier round of #1012 declined AZURE_CLIENT_SECRET
# on the "not live here" reading and was wrong on its own terms:
# tests/test_phase_4b_automation.sh drives the reviewer-adapter env allow-list

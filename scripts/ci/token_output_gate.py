class Finding:
    __slots__ = ("path", "line", "name", "reason")

    def __init__(self, path, line, name, reason):
        self.path = path
        self.line = line
        self.name = name
        self.reason = reason

    def __str__(self):
        return "%s:%d: %s reaches output via %s" % (
            self.path,
            self.line,
            self.name,
            self.reason,
        )


def scan_text(text, path="<text>"):
    """Return (findings, pragma_errors)."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    helpers = discover_emitter_helpers(text)
    lx = Lexer(text)
    findings = []
    pragma_errors = []
    for ll in lx.logical:
        if ll.pragma_bare and not ll.pragma_reasons:
            pragma_errors.append(
                "%s:%d: %s: with no reason -- the reason is mandatory"
                % (path, ll.first_line, PRAGMA)
            )
        if ll.pragma_reasons:
            continue
        for ref in ll.refs:
            hit, why = reaches_output(ref, helpers)
            if hit:
                findings.append(Finding(path, ref.line, ref.name, why))
    return findings, pragma_errors


# -- discovery -------------------------------------------------------------

_ENV_OPTS_WITH_ARG = {"-u", "--unset", "-C", "--chdir", "-S", "--split-string"}


def resolve_shebang(first_line):
    """Return the interpreter basename a `#!` line resolves to, or None.

    `None` means "this line named no interpreter I can resolve", and the
    caller then falls through to the extension and finally to SCANNING the
    file.  Nothing here may ever cause a file to be skipped: reducing
    `#!/usr/bin/env -S bash -e` to `-S` is precisely how #1012 turned a live
    `echo "$GH_TOKEN"` into `scanned 0 shell files` and `PASS`.

    Exercised directly by `_shebang_cases()`, not only through the
    file-selection corpus, so the `env` resolution is pinned on its own.
    """
    line = first_line.rstrip("\n").rstrip("\r")
    if not line.startswith("#!"):
        return None
    argv = line[2:].strip().split()
    if not argv:
        return None
    guard = 4
    while guard > 0:
        guard -= 1
        base = _basename(argv[0])
        if base != "env":
            return base
        argv = argv[1:]
        # consume env's own options and assignments
        while argv:
            a = argv[0]
            if a == "--":
                argv = argv[1:]
                break
            if a.startswith("--split-string="):
                argv = a.split("=", 1)[1].split() + argv[1:]
                break
            if a in ("-S", "--split-string"):
                if len(argv) < 2:
                    return None
                argv = argv[1].split() + argv[2:]
                break
            if a.startswith("-S"):
                argv = a[2:].split() + argv[1:]
                break
            if a in _ENV_OPTS_WITH_ARG:
                if len(argv) < 2:
                    return None
                argv = argv[2:]
                continue
            if a.startswith("--unset=") or a.startswith("--chdir="):
                argv = argv[1:]
                continue
            if a in ("-i", "--ignore-environment", "-0", "--null", "-v", "--debug"):
                argv = argv[1:]
                continue
            if re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", a):
                argv = argv[1:]
                continue
            if a.startswith("-"):
                # An env option this resolver does not model.  Return None so
                # the caller falls through to the extension and finally to
                # SCANNING the file, rather than reducing the interpreter to
                # the option itself -- which is exactly how `env -S` made a
                # file invisible in #1012.
                return None
            break
        if not argv:
            return None
    return None


def classify_file(path):
    """Return "shell" or "non-shell".  Raises CheckError when unclassifiable."""
    try:
        with open(path, "rb") as fh:
            head = fh.read(8192)
    except OSError as exc:
        raise CheckError("unreadable: %s" % exc)
    if b"\x00" in head:
        return "non-shell"
    try:
        first = head.split(b"\n", 1)[0].decode("utf-8", "replace")
    except Exception as exc:  # pragma: no cover - decode never raises here
        raise CheckError("undecodable head: %s" % exc)
    interp = resolve_shebang(first)
    if interp in SHELL_INTERPRETERS:
        return "shell"
    if interp in NON_SHELL_INTERPRETERS:
        return "non-shell"
    ext = os.path.splitext(path)[1].lower()
    if ext in SHELL_EXTS:
        return "shell"
    if ext in NON_SHELL_EXTS:
        return "non-shell"
    # Neither the shebang nor the extension settled it.  The FAIL-CLOSED
    # answer for a scanner is to READ the file, never to skip it: a file bash
    # will execute must be a file the gate reads, and a shell fragment with
    # neither a shebang nor a `.sh` (a sourced snippet, a frozen fixture
    # copied without its first line) is exactly what #1012's discovery
    # dropped on the floor.  Scanning a non-shell text file costs at most a
    # visible finding that a pragma or a rename settles; skipping a shell
    # file costs a silent PASS, which is the #951 shape this gate exists to
    # stop.  So the fallback is deliberately asymmetric.
    return "shell"


def discover_shell_files(root):
    """Walk the scan roots.  Every failure is fatal; nothing is skipped."""
    shell = []
    errors = []
    present_roots = 0
    for rel in SCAN_ROOTS:
        base = os.path.join(root, rel)
        if not os.path.isdir(base):
            continue
        present_roots += 1
        # Symlinks ARE followed, because a symlinked shell file is a file bash
        # will execute.  `seen` keeps a directory cycle from looping forever;
        # a gate that hangs is a gate that never reports.
        seen = set()
        for dirpath, dirnames, filenames in os.walk(base, followlinks=True):
            try:
                key = os.path.realpath(dirpath)
            except OSError as exc:
                errors.append("%s: unresolvable directory: %s" % (dirpath, exc))
                dirnames[:] = []
                continue
            if key in seen:
                dirnames[:] = []
                continue
            seen.add(key)
            dirnames[:] = sorted(d for d in dirnames if d != ".git")
            for name in sorted(filenames):
                p = os.path.join(dirpath, name)
                try:
                    st = os.stat(p)
                except OSError as exc:
                    errors.append("%s: unstattable: %s" % (p, exc))
                    continue
                if not stat.S_ISREG(st.st_mode):
                    errors.append("%s: not a regular file" % p)
                    continue
                try:
                    kind = classify_file(p)
                except CheckError as exc:
                    errors.append("%s: %s" % (p, exc))
                    continue
                if kind == "shell":
                    shell.append(p)
    return shell, errors, present_roots


def scan_tree(root):
    """Scan a tree.  Returns (findings, errors, count-of-shell-files)."""
    shell, errors, present_roots = discover_shell_files(root)
    if present_roots == 0:
        errors.append(
            "none of the scan roots %s exist under %s -- refusing to report a "
            "clean tree the gate never looked at" % (list(SCAN_ROOTS), root)
        )
    findings = []
    for p in shell:
        try:
            with open(p, "r", encoding="utf-8", errors="replace") as fh:
                text = fh.read()
        except OSError as exc:
            errors.append("%s: unreadable: %s" % (p, exc))
            continue
        f, pragma_errors = scan_text(text, os.path.relpath(p, root))
        findings.extend(f)
        errors.extend(pragma_errors)
    if not shell and not errors:
        errors.append(
            "scanned 0 shell files under %s -- a scan that selects no files is "
            "a discovery failure, never a clean tree" % root
        )
    return findings, errors, len(shell)



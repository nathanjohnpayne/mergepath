UNRESOLVED = "<unresolved>"


def _unquote_command_word(w):
    """Reduce a command word to a literal, or return None if it is not one."""
    out = []
    i = 0
    n = len(w)
    while i < n:
        c = w[i]
        if c == "\\" and i + 1 < n:
            out.append(w[i + 1])
            i += 2
            continue
        if c == "'":
            j = w.find("'", i + 1)
            if j == -1:
                return None
            out.append(w[i + 1 : j])
            i = j + 1
            continue
        if c == '"':
            j = i + 1
            buf = []
            while j < n and w[j] != '"':
                if w[j] == "\\" and j + 1 < n:
                    buf.append(w[j + 1])
                    j += 2
                    continue
                if w[j] in "$`":
                    return None
                buf.append(w[j])
                j += 1
            if j >= n:
                return None
            out.append("".join(buf))
            i = j + 1
            continue
        if c in "$`":
            return None
        out.append(c)
        i += 1
    lit = "".join(out)
    if not lit:
        return None
    return lit


def _basename(lit):
    if "/" in lit:
        lit = lit.rsplit("/", 1)[-1]
    return lit


def resolve_command(seg):
    """Return (command-word-literal | None | UNRESOLVED, has_redirection)."""
    if seg._resolved:
        return seg._cmd
    seg._resolved = True
    words = list(seg.words)
    # Output redirections are collected over the WHOLE segment, not just the
    # words ahead of the command.  `_v=$(printf '%s' "$PAT" >&2)` puts the
    # redirection AFTER the command word, and stopping at the command word is
    # how #1012 let that one escape the capture.
    has_redir = any(_OUT_REDIR_RE.match(w) for w in words)
    idx = 0
    passthru_budget = 6
    while idx < len(words):
        w = words[idx]
        if w in ("{", "}"):
            idx += 1
            continue
        if w == "<<" or w == "<<<":
            idx += 1
            continue
        if _ASSIGN_RE.match(w):
            idx += 1
            continue
        m = _REDIR_RE.match(w)
        if m:
            if m.end() == len(w):
                idx += 2  # operator and its target word
            else:
                idx += 1
            continue
        lit = _unquote_command_word(w)
        if lit is None:
            seg._cmd = (UNRESOLVED, has_redir)
            return seg._cmd
        if lit in RESERVED_WORDS:
            idx += 1
            continue
        base = _basename(lit)
        if base in PASSTHRU and passthru_budget > 0:
            passthru_budget -= 1
            idx += 1
            # step over the wrapper's own options / assignments
            while idx < len(words):
                nw = words[idx]
                nlit = _unquote_command_word(nw)
                if nlit is None:
                    seg._cmd = (UNRESOLVED, has_redir)
                    return seg._cmd
                if nlit == "--":
                    idx += 1
                    break
                if _ASSIGN_RE.match(nw):
                    idx += 1
                    continue
                if nlit.startswith("-"):
                    # env -u NAME / -C DIR / timeout -s SIG take an argument
                    if base == "env" and nlit in ("-u", "-C", "--unset", "--chdir"):
                        idx += 2
                        continue
                    if base == "timeout" and nlit in ("-s", "--signal", "-k"):
                        idx += 2
                        continue
                    if base == "stdbuf" and nlit in ("-i", "-o", "-e"):
                        idx += 2
                        continue
                    idx += 1
                    continue
                break
            if idx >= len(words):
                # a bare wrapper with no command: `env` alone dumps the
                # environment it was handed.
                seg._cmd = (base, has_redir)
                return seg._cmd
            continue
        seg._cmd = (base, has_redir)
        return seg._cmd
    seg._cmd = (None, has_redir)
    return seg._cmd


EMIT = "emit"
SAFE = "safe"
ASSIGN = "assign"
OPAQUE = "opaque"


def classify(seg, emitter_helpers):
    cmd, _redir = resolve_command(seg)
    if cmd is None:
        return ASSIGN
    if cmd is UNRESOLVED:
        return OPAQUE
    if cmd in OPAQUE_COMMANDS:
        return OPAQUE
    if cmd == "printf":
        lits = [_unquote_command_word(w) for w in seg.words]
        if "-v" in lits:
            return ASSIGN
        return EMIT
    if cmd in EMITTERS:
        return EMIT
    if cmd in emitter_helpers:
        return EMIT
    if cmd in ENV_DUMPERS:
        return EMIT
    if cmd in SAFE_COMMANDS:
        return SAFE
    return SAFE  # an external command: see "does NOT catch" in the header


def reaches_output(ref, emitter_helpers):
    """Does this reference reach a stream?  Returns (bool, reason)."""
    if ref.in_assign_prefix:
        # `GH_TOKEN="$PAT" cmd ...` puts the value in the child's ENVIRONMENT.
        cmd, _ = resolve_command(ref.seg)
        if cmd in ENV_DUMPERS:
            return True, (
                "an env-prefix assignment handed to %s, which dumps the "
                "environment it was given" % cmd
            )
        return False, ""

    # A here-doc body belongs to the command that OPENED it, which may be in a
    # later segment (`true; cat <<EOF`).  From there it walks out exactly like
    # any other reference, so a captured here-doc gets the same shield a
    # captured `printf` does.
    seg = ref.heredoc_owner if ref.heredoc_owner is not None else ref.seg
    note = "interpolating here-doc body" if ref.heredoc_owner is not None else None

    hops = 0
    via_stdin = False
    while seg is not None and hops < 32:
        hops += 1
        cmd, has_out_redir = resolve_command(seg)
        kind = classify(seg, emitter_helpers)
        if kind == OPAQUE:
            return True, "command word could not be resolved (%s)" % (
                "unresolvable" if cmd is UNRESOLVED else cmd
            )
        if via_stdin:
            # The value arrived on THIS segment's standard input, through a
            # pipe.  `echo` and `printf` write their ARGUMENTS and discard
            # stdin, so being an emitter says nothing here; only a command
            # that writes its stdin puts the value back on a stream.
            #
            # What any OTHER command does with a value handed to its stdin is
            # the same unmodelled question as a value handed to it as an
            # argument (`curl -H "...: $PAT"`), and the here-string spelling
            # of it -- `grep -qF x <<< "$PAT"` -- is already clean.  Flagging
            # the pipe spelling alone made the gate disagree with itself and
            # redded the canonical secure hand-off (`gh auth login
            # --with-token`, `docker login --password-stdin`); see the
            # "does NOT catch" list, which now names the whole class.
            if cmd is None:
                if not [w for w in seg.words if w not in ("{", "}")]:
                    # Not a simple command: a `{ ...; }` group, a `( ... )`
                    # subshell, or a `|&` consumer.  WHICH command inside the
                    # group reads the pipe is a dataflow question a
                    # single-line source-text scanner cannot answer, so this
                    # fails CLOSED.  Declared in KNOWN_BROADER.
                    return True, _why(
                        note,
                        "piped into a group whose consumer cannot be resolved",
                    )
                # An assignment-only consumer (`... | v=1`) runs no command
                # and writes nothing.
                return False, ""
            if cmd not in STDIN_ECHOERS:
                return False, ""
            kind = EMIT
            if note is None:
                note = "piped standard input"
        # `cat`/`tee` write their standard input, so a here-doc body or a
        # here-string handed to one is an emission by the same rule.
        elif kind != EMIT and cmd in STDIN_ECHOERS:
            if note is not None or "<<<" in seg.words:
                kind = EMIT
                if note is None:
                    note = "here-string"
        if kind != EMIT:
            return False, ""
        if seg.pipe_to is not None:
            # The value goes into the next segment's stdin rather than to a
            # terminal -- unless a redirection moves fd 1 somewhere the pipe
            # does not reach, which is the same escape the capture shield
            # below measures (`printf '%s' "$PAT" >&2 | grep -q x` reaches
            # the terminal on stderr).
            if redirects_stdout(seg):
                return True, _why(
                    note,
                    "%s whose output redirection escapes the pipeline"
                    % (cmd or "output command"),
                )
            seg = seg.pipe_to
            via_stdin = True
            continue
        if seg.parent_is_capture and seg.parent is not None:
            if has_out_redir:
                return True, _why(
                    note, "%s inside $( ), where an output redirection "
                    "escapes the capture" % cmd
                )
            seg = seg.parent
            via_stdin = False
            note = note  # the note travels out with the reference
            continue
        return True, _why(note, cmd or "output command")
    return True, "expansion nesting too deep to resolve"


def _why(note, base):
    return "%s written by %s" % (note, base) if note else base



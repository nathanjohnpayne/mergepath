def _generated_corpus():
    """Cross the three axes without a full Cartesian product.

    Every prefix meets every emitter, every emitter meets every reference
    spelling, and the rotation makes every (prefix, reference) pair appear
    too, so no axis is sampled at one fixed value of another.  A full product
    would be 672 fixtures and the oracle would take longer than the rest of
    repo_lint put together.
    """
    out = []
    for pi, (pre, suf) in enumerate(GEN_PREFIXES):
        for ei, emitter in enumerate(GEN_EMITTERS):
            ref = GEN_REFS[(pi + ei) % len(GEN_REFS)]
            out.append(
                (
                    "gen-emit-p%02d-e%d" % (pi, ei),
                    MUST_FLAG,
                    "%s%s %s%s\n" % (pre, emitter, ref, suf),
                )
            )
    for ei, emitter in enumerate(GEN_EMITTERS):
        for ri, ref in enumerate(GEN_REFS):
            out.append(
                (
                    "gen-emit-plain-e%d-r%d" % (ei, ri),
                    MUST_FLAG,
                    "%s %s\n" % (emitter, ref),
                )
            )
    for ti, (name, tmpl) in enumerate(GEN_CLEAN_TEMPLATES):
        for ri, ref in enumerate(GEN_REFS):
            if ref.startswith("$") and name in (
                "env-prefix",
                "env-prefix-varcmd",
                "assign",
                "export",
                "local-in-function",
            ):
                # an unquoted assignment RHS is legal shell but not a shape
                # anyone writes; skipping it keeps the corpus honest rather
                # than padded
                continue
            out.append(("gen-clean-%s-r%d" % (name, ri), MUST_NOT_FLAG, tmpl % ref))
    return out


CORPUS.extend(_generated_corpus())

# Disagreements with the oracle, DECLARED.  Each entry is a corpus id and the
# reason the scanner's verdict differs from what bash actually does.  The suite
# fails when an undeclared disagreement appears AND when a declared entry stops
# disagreeing, so neither list can quietly rot.
KNOWN_MISSES = {
    "indirect-rename": (
        "indirection -- the value is copied under a name the closed list does "
        "not carry, and this scanner has no dataflow"
    ),
    "indirect-loop-variable": (
        "indirection -- the loop variable holds the value; `for` is a safe "
        "command word and the later `echo` names only the loop variable"
    ),
    "indirect-printf-v": (
        "indirection -- `printf -v` assigns, and the later `echo` names only "
        "the assigned variable"
    ),
    "indirect-through-file": (
        "indirection through a file -- the write IS caught when it names the "
        "variable (pragma'd here to isolate the case); the later `cat` cannot "
        "be connected to it.  This is the shape of the check_resolve_pr_threads "
        "leak #993 fixed"
    ),
    "indirect-external-command": (
        "an external command is handed the value and prints it; this check "
        "knows what echo/printf/cat/tee do and does not model awk"
    ),
    "indirect-interpreter": (
        "the value reaches an interpreter that prints it; `bash -c` is opaque "
        "to a source-text scanner"
    ),
    "pragma-honoured": (
        "the pragma is a deliberate exemption -- the line does emit, and the "
        "written reason is the point"
    ),
}

KNOWN_BROADER = {
    "emitter-to-file": (
        "an emitter redirected to a FILE puts nothing on a stream, but the "
        "rule counts it: that write is the first hop of the "
        "check_resolve_pr_threads leak #993 fixed, and the gate is built so "
        "that hop is visible"
    ),
}


def run_oracle(body, workdir, name, shebang=None, run_via=None):
    """Ground truth: write the fixture, run it under bash, grep both streams."""
    path = os.path.join(workdir, name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = (shebang if shebang is not None else PROLOGUE) + body
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.chmod(path, 0o755)
    env = {
        "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
        "HOME": workdir,
        "LC_ALL": "C",
        "TMPDIR": workdir,
    }
    # Construct fixtures are handed to `bash` by name.  Executing the freshly
    # written file through its own shebang costs ~200ms per fixture on macOS
    # (the first exec of a new file goes through a security check), and the
    # shebang is not what a construct case is measuring; the file-selection
    # axis passes run_via=None precisely so the shebang IS exercised.
    argv = (run_via if run_via is not None else ["bash"]) + [path]
    try:
        proc = subprocess.run(
            argv,
            cwd=os.path.dirname(path),
            env=env,
            capture_output=True,
            timeout=20,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return None, "", "oracle could not run: %s" % exc
    out = proc.stdout.decode("utf-8", "replace")
    err = proc.stderr.decode("utf-8", "replace")
    return sentinel_reached(out, err), out, err


def self_test():
    failures = []
    passed = 0
    tp = fn = fp = tn = 0

    with tempfile.TemporaryDirectory(prefix="token-output-oracle.") as tmp:

        def _one(entry):
            cid, _disposition, body = entry
            fixture_dir = os.path.join(tmp, cid)
            os.makedirs(fixture_dir, exist_ok=True)
            return run_oracle(body, fixture_dir, "fixture.sh")

        workers = min(16, max(4, (os.cpu_count() or 4) * 2))
        with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
            oracle_results = list(pool.map(_one, CORPUS))

        for (cid, disposition, body), (leaked, out, err) in zip(
            CORPUS, oracle_results
        ):
            findings, pragma_errors = scan_text(PROLOGUE + body, cid + "/fixture.sh")
            flagged = bool(findings) or bool(pragma_errors)

            if disposition == MUST_FLAG and not flagged:
                failures.append(
                    "%s: the rule says FLAG and the scanner reported clean\n"
                    "    source: %s\n    oracle leaked: %s"
                    % (cid, body.strip().replace("\n", "\\n"), leaked)
                )
            elif disposition == MUST_NOT_FLAG and flagged:
                failures.append(
                    "%s: the rule says CLEAN and the scanner flagged %s\n"
                    "    source: %s"
                    % (
                        cid,
                        "; ".join(str(f) for f in findings) or pragma_errors,
                        body.strip().replace("\n", "\\n"),
                    )
                )
            else:
                passed += 1

            if leaked is None:
                failures.append("%s: %s" % (cid, err))
                continue

            # -- the differential ------------------------------------------
            if leaked and flagged:
                tp += 1
            elif leaked and not flagged:
                fn += 1
                if cid not in KNOWN_MISSES:
                    failures.append(
                        "FALSE NEGATIVE (undeclared): %s\n"
                        "    source: %s\n"
                        "    bash put the sentinel on a stream; the scanner "
                        "reported clean\n"
                        "    stdout: %r\n    stderr: %r"
                        % (cid, body.strip().replace("\n", "\\n"), out[:200], err[:200])
                    )
            elif (not leaked) and flagged:
                fp += 1
                if cid not in KNOWN_BROADER:
                    failures.append(
                        "FALSE POSITIVE (undeclared): %s\n"
                        "    source: %s\n"
                        "    bash put nothing on either stream; the scanner "
                        "flagged %s"
                        % (
                            cid,
                            body.strip().replace("\n", "\\n"),
                            "; ".join(str(f) for f in findings) or pragma_errors,
                        )
                    )
            else:
                tn += 1

            if cid in KNOWN_MISSES and not (leaked and not flagged):
                failures.append(
                    "STALE KNOWN_MISSES entry %r: it no longer disagrees with "
                    "the oracle (leaked=%s flagged=%s) -- delete it"
                    % (cid, leaked, flagged)
                )
            if cid in KNOWN_BROADER and not ((not leaked) and flagged):
                failures.append(
                    "STALE KNOWN_BROADER entry %r: it no longer disagrees with "
                    "the oracle (leaked=%s flagged=%s) -- delete it"
                    % (cid, leaked, flagged)
                )

        failures.extend(_shebang_cases())
        failures.extend(_pragma_cases())
        failures.extend(_file_selection_cases(tmp))
        failures.extend(_discovery_failure_cases(tmp))
        failures.extend(_path_independence_case(tmp))

    failures.extend(_residue_and_quoted_tmpdir_case())

    total = tp + fn + fp + tn
    print(
        "check_no_token_in_output: oracle differential over %d constructs -- "
        "%d agree, %d declared misses, %d declared conservative"
        % (total, tp + tn, fn, fp)
    )
    print(
        "check_no_token_in_output: rule cases %d/%d"
        % (passed, len(CORPUS))
    )
    # The header's "does NOT catch" list is re-derived from THIS, not the
    # other way round: every entry below is a live corpus case whose
    # disagreement with bash was measured on this run.  An absence from it is
    # not coverage.
    for cid in sorted(KNOWN_MISSES):
        print(
            "check_no_token_in_output:   measured miss: %s -- %s"
            % (cid, KNOWN_MISSES[cid])
        )
    for cid in sorted(KNOWN_BROADER):
        print(
            "check_no_token_in_output:   measured conservatism: %s -- %s"
            % (cid, KNOWN_BROADER[cid])
        )
    if failures:
        for f in failures:
            print("check_no_token_in_output: FAIL: %s" % f, file=sys.stderr)
        return 1
    return 0



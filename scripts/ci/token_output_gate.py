#!/usr/bin/env python3
r"""token_output_gate --- the enforcement half of #951 / #993 / #996.

Invoked through `scripts/ci/check_no_token_in_output`, the shell launcher
repo_lint wires; that file is three lines of dispatch and this one is the
gate.  Run it either way -- the launcher passes its arguments straight
through.

#951 found a live PAT printed in cleartext by a checker's own failure message.
#993 fixed the three sites it could find by grepping `scripts/` for five
variable names and executing every checker that matched under a sentinel
environment.  That is a point-in-time measurement: nothing mechanically stops
the next checker from reintroducing the shape.  This check is the mechanism.

THE RULE

    Under scripts/** and tests/**, a shell source line may not interpolate the
    VALUE of a known credential variable into an output command.

=========================================================================
WHY THIS FILE IS A REBUILD (#1015)
=========================================================================

The first attempt (#1012, closed and parked) decided "is this an output
command, and does this reference reach it" with a hand-written character walk,
and every review round found a NEW shell spelling the walk did not model --
five direct-form escapes were still live at close.  The list of shell spellings
is not a finite thing a reviewer can close by inspection, and 51 hand-written
fixtures could only assert what their author had already thought of.

So the deciding question is not "which constructs should the walk model?"  It
is "does this line put the value on a stream?", and that question is
EXECUTABLE.  This file carries both halves:

  * THE GATE is a STATIC scanner.  It runs in CI over a repository and never
    executes the source it scans.  Executing arbitrary repository source in CI
    would be unsafe, and its behaviour under a runner's environment would say
    nothing about its behaviour anywhere else.

  * THE ORACLE is for the TEST SUITE ONLY (`--self-test`).  For each construct
    in the corpus it writes a disposable fixture carrying an obviously fake
    sentinel in a credential-named variable, runs it under `bash` in a
    throwaway temp tree with a scrubbed environment, captures stdout AND
    stderr separately, and greps both for the sentinel.  That is GROUND TRUTH:
    the construct leaks or it does not, independent of anyone's opinion.  The
    fixtures are generated by this file; no repository source is ever executed.

    The suite then asserts the static scanner AGREES with the oracle on every
    construct.  A construct the oracle says leaks and the scanner calls clean
    is a FALSE NEGATIVE; a construct the oracle says is clean and the scanner
    flags is scanner conservatism.  Both must be DECLARED in `KNOWN_MISSES` or
    `KNOWN_BROADER` with a written reason, or the suite fails and prints the
    offending line together with the captured streams.  A declared entry that
    stops disagreeing also fails, so neither registry can quietly rot.

    This is the shape `check_doc_ownership` uses with markdown-it-py and the
    shape `markdown-target-parser-is-cmark-gfm` records: measure against the
    real implementation instead of reasoning about a specification.

=========================================================================
WHAT "KNOWN CREDENTIAL VARIABLE" MEANS (#996 design question 1)
=========================================================================

A CLOSED, EXPLICIT NAME LIST (`TOKEN_NAMES` below) -- not a heuristic over
names matching TOKEN / PAT / SECRET / KEY.  Carried unchanged from #1012,
where it survived five review rounds without a finding against it.

The list loses recall: a credential reached under some other name is invisible
to it.  That is the deliberate trade.  This check runs inside repo_lint, which
publishes the REQUIRED `lint` context, and repo_lint propagates to every
consumer repo -- so one false positive reds a required check across the fleet
with no break-glass.  A gate that is right about a smaller set beats one that
is broadly right and occasionally wrong.

The heuristic is also wrong on this tree, not just in principle.  A `*TOKEN*`
name match fires on `SUMMARY_ACK_TOKEN` / `ACK_TOKEN` (the
mergepath-summary-ack marker), `MERGEPATH_EXPECT_READ_GH_TOKEN` and
`STEP_NO_TOKEN` (flags), and `BOOTSTRAP_SKIP_AUTHOR_TOKEN` (a switch) -- none
of which hold credential material.  Every one would need an allow-list entry,
and that allow-list is then the thing nine repos have to get right.

Extending the list is a one-line edit here, in mergepath, which propagates to
every consumer with the rest of the scripts/ci kit.

=========================================================================
HOW LEGITIMATE EMITTERS ARE EXEMPTED (#996 design question 2)
=========================================================================

An INLINE PRAGMA, visible at the site, never a path allow-list:

    printf 'export OP_PREFLIGHT_REVIEWER_PAT=%q\n' "$OP_PREFLIGHT_REVIEWER_PAT"  # TOKEN_OUTPUT_EXEMPT: <reason>

The reason is MANDATORY -- a bare `TOKEN_OUTPUT_EXEMPT:` with nothing after it
still fails, the same hardening `NO_BARE_GH_WRITE_EXEMPT` got in #466.
`scripts/op-preflight.sh` is the canonical legitimate emitter: writing those
values to its cache IS its contract.

The marker counts ONLY inside a real shell comment -- a `#` that is unquoted,
unescaped, word-initial, and at parameter-expansion nesting depth zero.  #1012
was bypassable in two independent ways and both are re-established here as
properties with oracle-backed cases rather than inherited as patches:

  * `printf '%s %s\n' "$GH_TOKEN" 'TOKEN_OUTPUT_EXEMPT: text'` -- the marker is
    quoted DATA.  The command still runs and still writes the value.
  * `echo "$GH_TOKEN" ${UNSET:+ # TOKEN_OUTPUT_EXEMPT: bypass}` -- `${...}` is
    a parameter expansion, not a command context, so bash starts NO comment at
    that `#` and prints the value.

Both are corpus entries, both oracle-confirmed leaking, both flagged.

The pragma is a REVIEW MARKER, not a security boundary.  Anyone editing the
file can silence this check -- by adding the pragma, by renaming the variable,
by any of the indirections below.  What it buys is that every deliberate
emission is greppable and carries a written reason.

THERE ARE NO PATH ALLOW-LISTS ANYWHERE IN THIS CHECK.  The only path decision
it makes is which files are shell at all.  A corpus case pins that moving an
exempt line into a different file does not change its verdict.

=========================================================================
WHAT COUNTS AS OUTPUT, AND WHAT COUNTS AS CAPTURE
=========================================================================

  * `echo` / `printf` at a command position.  Command words are matched by
    BASENAME, so `/bin/echo` and `./1/echo` are the same emitter.  A shell
    reserved word is not the command -- the command follows it -- so
    `if echo "$PAT"; then` is the same emitter.  A leading redirection and an
    option-bearing wrapper (`env -i echo ...`) are stepped over.  An escaped
    command word (`\echo`) is the same emitter.  `printf -v NAME` is NOT
    output: bash assigns to a variable instead of writing to a stream.
  * An in-file message helper: a function whose body writes one of its own
    positional parameters VERBATIM through an emitter.  Both definition forms
    count.  Body extraction is brace-depth counted over lexer state, so a
    nested block whose closing brace starts its own line does not end it early.
  * The body of an INTERPOLATING here-doc (unquoted delimiter) owned by `cat`,
    `tee` or an emitter.  ALL here-doc openers on a line are tracked, not just
    the first (#1014), and the owner is the command of the SEGMENT the opener
    appears in, so `true; cat <<EOF` attributes the body to `cat`.
  * The word of a here-STRING given to one of those same commands.

CAPTURE IS NOT EMISSION.  In `_v=$(printf '%s' "$GH_TOKEN")` the value goes
into a variable.  The shield is conditional, because #1012 measured the escape:
`_v=$(printf '%s' "$GH_TOKEN" >&2)` redirects past the capture and reaches the
terminal.  So a captured emitter counts as capture only when the emitting
segment carries NO redirection at all; any redirection inside the substitution
is flagged.  A subshell or brace group is not a capture: `( echo "$PAT" )`
is flagged.

REDACTION IS NOT EMISSION.  `${#VAR}` is a length and `${VAR:+set}` is a
constant alternate; neither is a value reference, so both are legal with no
pragma -- they are the #993 remediation and adopting it never trips the gate.
`${VAR:+$VAR}` carries its own expansion and the inner reference is flagged on
its own.  A helper that derives a length or a class and prints that is
therefore not a message helper, so `key_state "$PAT"` stays legal.

=========================================================================
WHAT THIS CHECK DOES NOT CATCH
=========================================================================

Re-derived from what the harness ACTUALLY shows, not from what the author
believes.  Every entry below is a live corpus case whose disagreement with the
oracle is declared in `KNOWN_MISSES`, and `--self-test` PRINTS that registry on
every run, so this prose cannot drift away from the measurement -- if the two
ever disagree, the printed list is the true one.

READ IT AS THE MEASURED SAMPLE IT IS: an absence from this list is NOT
coverage.  The scanner is a source-text approximation; the oracle is the only
thing here that knows the truth, and it only knows it about constructs someone
put in the corpus.

INDIRECTION IS NOT COVERED.  This is a single-hop source-text scanner over one
logical line at a time, with no dataflow, no cross-file analysis, and no
knowledge of what a variable holds at runtime.  It does not catch:

  * A token copied into a differently-named variable and then printed
    (`pat=$OP_PREFLIGHT_AUTHOR_PAT; echo "$pat"`), or reached through a
    function return, a `read`, a `printf -v`, a loop variable, or `$(op read
    ...)`.
  * A token written to a log or temp file that some later line prints
    (`cat "$LOG"`).  It DOES catch the line that puts the value into the log,
    when that line names the variable; it cannot connect that line to the `cat`
    that prints it.
  * `set -x` traces, core dumps, or anything the shell emits on its own.  An
    `env`/`printenv`/`set` reached through a LITERAL command word IS caught,
    including behind an env-prefix assignment; one reached through a variable
    is not, because nothing in the source text says what it is.
  * A token handed to an EXTERNAL command as an argument
    (`curl -H "Authorization: Bearer $CF_API_TOKEN"`).  This check knows what
    `echo`, `printf`, `cat` and `tee` do with their arguments and does not
    pretend to know what anything else does.  Deliberate: flagging every
    external command that receives a credential would red a required
    fleet-wide check on the ordinary way credentials are passed.
  * A token reaching an interpreter that then prints it (`bash -c ...`,
    `python3 -c ...`, `awk -v ...`, a `bash <<EOF` here-doc).
  * Any file this check does not scan: non-shell files, and everything outside
    scripts/** and tests/**.

CONSERVATISM RUNS THE OTHER WAY IN ONE PLACE, also measured: an emitter
redirected to a FILE (`printf '%s\n' "$PAT" > log`) puts nothing on a stream,
and the gate flags it anyway.  That write is the FIRST HOP of the
check_resolve_pr_threads leak #993 fixed, and the gate is built so that hop
stays visible.  It is the only declared conservatism.

STATED PLAINLY, because #993's lesson was that an unstated limit reads as a
guarantee: NONE of the three leaks #993 fixed would have been caught by this
gate at their original sites.  All three reached the token under another name
or through a file.  This gate stops the DIRECT form from coming back; it is
not a proof that no credential can reach a stream.

And the recall claim is bounded by the CORPUS, not by an argument.  What the
harness demonstrates is that on 340 constructs -- generated across line
spellings, file selection and legal-but-unusual precision shapes -- the
scanner and bash agree except for the declared entries.  A construct nobody
wrote into the corpus is not covered by that statement.  Adding one is a
three-line edit to `CORPUS`, and the oracle decides it.

Related and equally out of reach (#1021): `scripts/op-preflight.sh` writing
export lines carrying live PAT values to ITS OWN stdout is a CALLER-side
problem.  That emission is the script's contract when its output is consumed by
`eval`, and a leak when a caller lets it reach a transcript.  No source-text
rule over `scripts/**` can separate the two, because the difference is in the
caller, not in the line.  The three op-preflight emitters carry
`TOKEN_OUTPUT_EXEMPT` pragmas so the decision is greppable; that is all a
source-text gate can do here.

=========================================================================
FILE DISCOVERY FAILS CLOSED
=========================================================================

#1012 shipped a discovery that failed OPEN: `#!/usr/bin/env -S bash -e` on an
extensionless script reduced the interpreter to `-S`, so the file was not
recognised as shell at all and a tree whose only file was such a script,
containing a live `echo "$GH_TOKEN"`, reported `scanned 0 shell files` and
PASS.  That is the #951 shape -- a green gate saying nothing was wrong --
reproduced inside the gate built to stop #951.

Here the property asserted is: A FILE BASH WILL EXECUTE IS A FILE THE GATE
READS, and every branch that cannot establish it is FATAL, not skipped:

  * A shebang is resolved through `env`, including `-S` / `--split-string=`,
    `-i`, `-u NAME`, `-C DIR` and `NAME=VALUE` assignments.
  * A file whose interpreter or extension classifies as neither shell nor
    known-non-shell is an ERROR, not a skip.
  * An unreadable path, or a traversal failure, is an ERROR.
  * A scan selecting ZERO shell files is an ERROR.  `scanned 0` can never be
    an advisory count on a PASS line again; a corpus case asserts it directly.

Usage:
    check_no_token_in_output              # self-test, then scan this repo
    check_no_token_in_output --self-test  # oracle-differential suite only
    check_no_token_in_output --scan [DIR] # scan only (default: this repo)

`--scan DIR` is also how the fleet measurement is taken: pointing it at
mergepath plus the nine consumer checkouts is the ten-tree hit-set comparison
#1015 asks for.  It is deliberately NOT a CI step -- CI has one tree, and a
step that cloned nine repositories to lint one would be a different kind of
gate.  The numbers from that run belong in the PR body, where a reviewer can
see them.

Exit codes: 0 pass, 1 findings or a failing case, 2 usage/environment error.
"""


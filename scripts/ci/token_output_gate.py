#
# Four names from that same fixture stay absent, and not because anyone forgot:
# GOOGLE_APPLICATION_CREDENTIALS, OP_PREFLIGHT_ADC_TMPFILE and
# OP_PREFLIGHT_FIREBASE_SA_TMPFILE are FILE PATHS and SSH_AUTH_SOCK is a socket
# path -- printing one leaks no secret, and op-preflight.sh prints
# GOOGLE_APPLICATION_CREDENTIALS deliberately and without a pragma, so
# admitting it would red a required check over a legitimate line.

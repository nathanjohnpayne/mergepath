UNRESOLVED = "<unresolved>"


def _unquote_command_word(w):
    """Reduce a command word to a literal, or return None if it is not one."""
    out = []
    i = 0
    n = len(w)
    while i < n:
        c = w[i]
        if c == "\\" and i + 1 < n:
            out.append(w[i + 1])
            i += 2
            continue
        if c == "'":
            j = w.find("'", i + 1)
            if j == -1:
                return None
            out.append(w[i + 1 : j])
            i = j + 1
            continue
        if c == '"':
            j = i + 1
            buf = []
            while j < n and w[j] != '"':
                if w[j] == "\\" and j + 1 < n:
                    buf.append(w[j + 1])
                    j += 2
                    continue
                if w[j] in "$`":
                    return None
                buf.append(w[j])
                j += 1
            if j >= n:
                return None
            out.append("".join(buf))
            i = j + 1
            continue
        if c in "$`":
            return None
        out.append(c)
        i += 1
    lit = "".join(out)
    if not lit:
        return None
    return lit


def _basename(lit):
    if "/" in lit:
        lit = lit.rsplit("/", 1)[-1]
    return lit


def resolve_command(seg):
    """Return (command-word-literal | None | UNRESOLVED, has_redirection)."""
    if seg._resolved:
        return seg._cmd
    seg._resolved = True
    words = list(seg.words)
    # Redirections are collected over the WHOLE segment, not just the words
    # ahead of the command.  `_v=$(printf '%s' "$PAT" >&2)` puts the
    # redirection AFTER the command word, and stopping at the command word is
    # how #1012 let that one escape the capture.
    has_redir = any(
        w in ("<<", "<<<") or _REDIR_RE.match(w) for w in words
    )
    idx = 0
    passthru_budget = 6
    while idx < len(words):
        w = words[idx]
        if w in ("{", "}"):
            idx += 1
            continue
        if w == "<<" or w == "<<<":
            idx += 1
            continue
        if _ASSIGN_RE.match(w):
            idx += 1
            continue
        m = _REDIR_RE.match(w)
        if m:
            if m.end() == len(w):
                idx += 2  # operator and its target word
            else:
                idx += 1
            continue
        lit = _unquote_command_word(w)
        if lit is None:
            seg._cmd = (UNRESOLVED, has_redir)
            return seg._cmd
        if lit in RESERVED_WORDS:
            idx += 1
            continue
        base = _basename(lit)
        if base in PASSTHRU and passthru_budget > 0:
            passthru_budget -= 1
            idx += 1
            # step over the wrapper's own options / assignments
            while idx < len(words):
                nw = words[idx]
                nlit = _unquote_command_word(nw)
                if nlit is None:
                    seg._cmd = (UNRESOLVED, has_redir)
                    return seg._cmd
                if nlit == "--":
                    idx += 1
                    break
                if _ASSIGN_RE.match(nw):
                    idx += 1
                    continue
                if nlit.startswith("-"):
                    # env -u NAME / -C DIR / timeout -s SIG take an argument
                    if base == "env" and nlit in ("-u", "-C", "--unset", "--chdir"):
                        idx += 2
                        continue
                    if base == "timeout" and nlit in ("-s", "--signal", "-k"):
                        idx += 2
                        continue
                    if base == "stdbuf" and nlit in ("-i", "-o", "-e"):
                        idx += 2
                        continue
                    idx += 1
                    continue
                break
            if idx >= len(words):
                # a bare wrapper with no command: `env` alone dumps the
                # environment it was handed.
                seg._cmd = (base, has_redir)
                return seg._cmd
            continue
        seg._cmd = (base, has_redir)
        return seg._cmd
    seg._cmd = (None, has_redir)
    return seg._cmd


EMIT = "emit"
SAFE = "safe"
ASSIGN = "assign"
OPAQUE = "opaque"


def classify(seg, emitter_helpers):
    cmd, _redir = resolve_command(seg)
    if cmd is None:
        return ASSIGN
    if cmd is UNRESOLVED:
        return OPAQUE
    if cmd in OPAQUE_COMMANDS:
        return OPAQUE
    if cmd == "printf":
        lits = [_unquote_command_word(w) for w in seg.words]
        if "-v" in lits:
            return ASSIGN
        return EMIT
    if cmd in EMITTERS:
        return EMIT
    if cmd in emitter_helpers:
        return EMIT
    if cmd in ENV_DUMPERS:
        return EMIT
    if cmd in SAFE_COMMANDS:
        return SAFE
    return SAFE  # an external command: see "does NOT catch" in the header


def reaches_output(ref, emitter_helpers):
    if ref.heredoc_owner is not None:
        owner = ref.heredoc_owner
        cmd, _ = resolve_command(owner)
        if cmd is UNRESOLVED or cmd in OPAQUE_COMMANDS:
            return True, "here-doc body owned by an unresolvable command"
        if cmd in STDIN_ECHOERS:
            return True, "interpolating here-doc body written by %s" % cmd
        if classify(owner, emitter_helpers) == EMIT:
            return True, "interpolating here-doc body written by %s" % cmd
        return False, ""
    if ref.in_assign_prefix:
        cmd, _ = resolve_command(ref.seg)
        if cmd in ENV_DUMPERS:
            return True, "an env-prefix assignment handed to %s, which dumps "\
                "the environment it was given" % cmd
        return False, ""
    seg = ref.seg
    hops = 0
    while seg is not None and hops < 16:
        hops += 1
        kind = classify(seg, emitter_helpers)
        cmd, has_redir = resolve_command(seg)
        if kind == OPAQUE:
            return True, "command word could not be resolved (%s)" % (
                "unresolvable" if cmd is UNRESOLVED else cmd
            )
        if kind != EMIT:
            if "<<<" in seg.words and cmd in STDIN_ECHOERS:
                return True, "here-string written by %s" % cmd
            return False, ""
        if seg.parent_is_capture and seg.parent is not None:
            if has_redir:
                return True, (
                    "%s inside $( ), where a redirection escapes the capture"
                    % cmd
                )
            seg = seg.parent
            continue
        return True, cmd or "output command"
    return True, "expansion nesting too deep to resolve"


